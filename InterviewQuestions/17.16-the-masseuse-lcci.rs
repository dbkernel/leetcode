/*
============================================================================
面试题 17.16. 按摩师（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/the-masseuse-lcci/
分类：动态规划 · 线性递推（相邻约束）

一个有名的按摩师会收到源源不断的预约请求，每个预约都可以选择接或不接。在每次预约服务之间要有休息时间，因此她不能接受相邻的预约。给定一个预约请求序列，替按摩师找到最优的预约集合（总预约时间最长），返回总的分钟数。

注意：本题相对原题稍作改动

示例 1：
输入： [1,2,3,1]
输出： 4
解释： 选择 1 号预约和 3 号预约，总时长 = 1 + 3 = 4。

示例 2：
输入： [2,7,9,3,1]
输出： 12
解释： 选择 1 号预约、 3 号预约和 5 号预约，总时长 = 2 + 9 + 1 = 12。

示例 3：
输入： [2,1,4,5,3,1,1,3]
输出： 12
解释： 选择 1 号预约、 3 号预约、 5 号预约和 8 号预约，总时长 = 2 + 4 + 3 + 3 = 12。

提示：
- 0 <= 预约数量 <= 100
*/

/*
解法一：二维 DP，把"接不接第 i 个预约"拆成两个状态【非最优】

为什么慢：对每个预约枚举接或不接，是 2^n 种组合；即便按"相邻不能都接"
剪枝，仍然要在搜索树上回溯，规模到 100 就不可行。

换个角度：与 198 打家劫舍完全同构——约束只发生在相邻两项之间，所以
"前 i 个预约的最优值"只需要知道第 i 个接没接。把这一位拆成状态即可。

关键点：
  · dp[i][1] 只能由 dp[i-1][0] 转移，这是"相邻不可同时接"的唯一落点
  · dp[i][0] 两条来源取 max：第 i 个不接时，第 i-1 个接不接都合法
  · dp[i] 描述"前 i 个预约"，时长取 nums[i-1]，两处下标错开一位
  · dp[0][*] = 0 同时覆盖两件事：没有预约，以及预约时长为 0 的极端情况
  · Rust 里用 [[i32; 2]] 而不是两个平行 Vec，减少一次下标换算

以示例 2（nums = [2,7,9,3,1]）为例，每步写 (不接, 接)：
  i=1： (0, 2)
  i=2： (max(0,2)=2, 0+7=7)
  i=3： (max(2,7)=7, 2+9=11)
  i=4： (max(7,11)=11, 7+3=10)
  i=5： (max(11,10)=11, 11+1=12)
  答案 max(11,12) = 12 ✔

复杂度分析：
  时间 O(n)：每个预约两次常数转移
  空间 O(n)：n+1 行的两列状态表
*/
pub struct Solution1;

impl Solution1 {
    pub fn massage(nums: Vec<i32>) -> i32 {
        let n = nums.len();
        // dp[i][0] / dp[i][1]：前 i 个预约里，第 i 个不接 / 接 的最长时长
        let mut dp = vec![[0i32; 2]; n + 1];

        for i in 1..=n {
            dp[i][0] = dp[i - 1][0].max(dp[i - 1][1]);
            // 接第 i 个，则第 i-1 个必须放弃
            dp[i][1] = dp[i - 1][0] + nums[i - 1];
        }

        dp[n][0].max(dp[n][1])
    }
}

/*
解法二：一维滚动，只留两个变量【最优解】

为什么慢：解法一只需要相邻一行，却存了 n+1 行；本题最优值只由"前一个
的最优"和"前两个的最优"决定，整张表都是浪费。

换个角度：直接记 dp[i] = 前 i 个预约的最长时长，则要么不接第 i 个
（dp[i-1]），要么接第 i 个（dp[i-2] + nums[i-1]）。两个变量滚起来即可。

关键点：
  · 转移是 dp[i] = max(dp[i-1], dp[i-2] + x)，第二项必须跳过相邻那个预约，
    写成 max(dp[i-1], x) 就退化成贪心，示例 2 会得到 10 而不是 12
  · cur 用旧的 prev2、prev1 算完再整体后移
  · 与 198 的差别只在边界：198 保证至少一间房，这里预约数量可以是 0，
    答案必须是 0。滚动写法按值迭代、不碰 nums[0]，空切片天然返回 0
  · 时长非负，所以"一个都不接"永远合法，初值 0 不需要特判

以示例 2（nums = [2,7,9,3,1]）为例，记 (prev2, prev1)：
  初值 (0, 0)
  x=2：cur = max(0, 0+2) = 2 → (0, 2)
  x=7：cur = max(2, 0+7) = 7 → (2, 7)
  x=9：cur = max(7, 2+9) = 11 → (7, 11)
  x=3：cur = max(11, 7+3) = 10 → (11, 10)
  x=1：cur = max(10, 11+1) = 12 → (10, 12) ✔

复杂度分析：
  时间 O(n)：每个预约一次 max
  空间 O(1)：只有 prev2 / prev1 / cur 三个整数
*/
pub struct Solution2;

impl Solution2 {
    pub fn massage(nums: Vec<i32>) -> i32 {
        // prev2 / prev1 分别是 dp[i-2] / dp[i-1]
        let (mut prev2, mut prev1) = (0, 0);

        for x in nums {
            let cur = prev1.max(prev2 + x);
            prev2 = prev1;
            prev1 = cur;
        }

        prev1
    }
}

fn check(nums: &[i32], want: i32) {
    assert_eq!(Solution1::massage(nums.to_vec()), want);
    assert_eq!(Solution2::massage(nums.to_vec()), want);
}

fn main() {
    // 示例 1：接 1、3 两个预约
    check(&[1, 2, 3, 1], 4);

    // 示例 2：贪心拿 9 只能得 10，正确答案是 2+9+1
    check(&[2, 7, 9, 3, 1], 12);

    // 示例 3：2+4+3+3，跨过 5 和最后两个 1
    check(&[2, 1, 4, 5, 3, 1, 1, 3], 12);

    // 边界：首尾两项不相邻，2+9 = 11 优于相邻的 1+4
    check(&[2, 1, 4, 9], 11);

    // 关键点用例：空输入必须返回 0 —— 198 不会遇到这种输入，这里会
    check(&[], 0);

    // 边界：单个预约，直接接
    check(&[4], 4);

    // 边界：时长全为 0，答案 0 而不是 -1
    check(&[0, 0, 0], 0);

    // 关键点用例：隔一个接一个，2+2 与 1+1 都等于 4
    check(&[2, 1, 1, 2], 4);

    // 边界：100 个预约全为 100，只能隔一个接一个，答案 5000
    check(&vec![100; 100], 5000);

    println!("all tests passed");
}
