/*
============================================================================
面试题 05.07. 配对交换（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/exchange-lcci/
分类：位运算 · 掩码拆分奇偶位

配对交换。编写程序，交换某个整数的奇数位和偶数位，尽量使用较少的指令
（也就是说，位 0 与位 1 交换，位 2 与位 3 交换，以此类推）。

示例 1：
输入：num = 2（或者 0b10）
输出：1 (或者 0b01)

示例 2：
输入：num = 3
输出：3

提示：
- num 的范围在 [0, 2^30 - 1] 之间，不会发生整数溢出。
*/
package main

import "fmt"

/*
解法：两个掩码分别抠出奇偶位，一个右移、一个左移后合并【最优解】

官方提示给的就是这条路：用 0xAAAAAAAA 与 0x55555555 提取偶数位和奇数位，
再把它们各自移到相邻位上。它同时是本题的最优解 —— 指令数固定为常数条，
不可能更少。

为什么慢：逐位交换要把每一位单独取出来、放到相邻位上，共 16 轮，每轮
两次移位加一次按位或，指令数随位宽线性增长；而这件事本身是「整体搬家」，
根本不需要一位一位地搬。

换个角度：所有奇数位一起右移一位，所有偶数位一起左移一位，两批位的目的地
互不重叠，因此可以一次性并行完成。用两个掩码把两批位抠出来即可。

关键点：
  · 0xAAAAAAAA 的 1 落在奇数位（第 1、3、5……位），0x55555555 落在偶数位
    （第 0、2、4……位）；掩码写反了会得到「每位都变成 1」
  · 顺序是先 & 再移位：先移位会把相邻位的值带进来，掩码就白做了
  · 两半移位后直接按位或合并：两批位的目标位置互不重叠，不存在覆盖
  · Go 里 & 与 >> 的优先级：移位高于按位与，所以必须显式加括号，否则
    `num & 0xAAAAAAAA >> 1` 会被解析成 `num & (0xAAAAAAAA >> 1)`
  · num 最大到 2^30 - 1，最高只到第 29 位，左移一位不会超出 32 位

手推一遍（num = 2，0b10）：
  偶数位：0010 & 0101 = 0000 → 左移一位 → 0000
  奇数位：0010 & 1010 = 0010 → 右移一位 → 0001
  合并：0000 | 0001 = 0001 = 1 ✔

以 num = 3（0b11）为例：
  偶数位：0011 & 0101 = 0001 → 左移一位 → 0010
  奇数位：0011 & 1010 = 0010 → 右移一位 → 0001
  合并：0010 | 0001 = 0011 = 3 ✔（每一位都和邻居相同，交换后不变）

复杂度分析：
  时间 O(1)：固定 2 次与、1 次右移、1 次左移、1 次或
  空间 O(1)：只用两个中间变量
*/

// 交换 num 的奇数位与偶数位
func exchangeBits(num int) int {
	// 奇数位整体右移一位，落到原来的偶数位位置上
	odd := (num & 0xAAAAAAAA) >> 1
	// 偶数位整体左移一位，落到原来的奇数位位置上
	even := (num & 0x55555555) << 1

	// 两批位的目标位置互不重叠，直接用或合并
	return odd | even
}

// ---- 以下为自测代码，不属于题解主体 ----

func check(num, want int) {
	if got := exchangeBits(num); got != want {
		panic(fmt.Sprintf("exchangeBits(%d) = %d, want %d", num, got, want))
	}
}

func main() {
	// 示例 1：唯一的 1 在第 1 位，交换后落到第 0 位
	check(2, 1)

	// 示例 2：相邻两位都是 1，交换后仍是 3
	check(3, 3)

	// 边界：0，任何一位都不能被凭空造出来
	check(0, 0)

	// 边界：只有最低位是 1，交换后升到第 1 位
	check(1, 2)

	// 边界：高位参与交换（第 28、29 位）
	check(1<<29, 1<<28)
	check(1<<28, 1<<29)

	// 边界：以上限 2^30 - 1 全 1，交换后仍是全 1
	check((1<<30)-1, (1<<30)-1)

	// 边界：奇数位全 1 与偶数位全 1 互为映射，验证两组互不污染
	check(0x2AAAAAAA, 0x15555555)
	check(0x15555555, 0x2AAAAAAA)

	fmt.Println("all tests passed")
}
