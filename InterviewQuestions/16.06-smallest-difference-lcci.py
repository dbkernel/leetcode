"""
============================================================================
面试题 16.06. 最小差（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/smallest-difference-lcci/
分类：双指针 · 排序后归并收割

给定两个整数数组a和b，计算具有最小差绝对值的一对数值（每个数组中取一个值），
并返回该对数值的差

示例：
输入：{1, 3, 15, 11, 2}, {23, 127, 235, 19, 8}
输出：3，即数值对(11, 8)

提示：
- 1 <= a.length, b.length <= 100000
- -2147483648 <= a[i], b[i] <= 2147483647
- 正确结果在区间 [0, 2147483647] 内
"""


"""
解法一：暴力枚举所有数对【非最优】

为什么慢：题目要的就是"每个数组各取一个值，使差的绝对值最小"。最直白的
做法是把 n*m 个数对全部算一遍，n、m 都到 10^5 时是 10^10 次比较，必然超时。
瓶颈在于"抽出一个数之后，另一个数组里离它最近的数"这件事，暴力是挨个试，
没有利用任何顺序信息。

换个角度：如果两个数组都有序，"离 x 最近的 b 元素"就只可能在双指针当前
停留的位置附近 —— 因为一旦知道 b[j] 已经大于 a[i]，b[j] 之后的所有元素
离 a[i] 只会更远，这条信息让一整段候选被一次性排除。

关键点：
  · 差值在 C++/Go/Rust 里要用 64 位算：a[i] = 2^31-1、b[j] = -2^31 时
    差是 4294967295，超出 32 位；Python 的 int 是任意精度，不存在这一步，
    但换成别的语言照抄时必须先扩宽类型
  · 返回 int 是安全的：题面保证正确结果落在 [0, 2147483647]
  · 任一数组为空时没有可比的数对，返回 0

以示例（a = {1,3,15,11,2}，b = {23,127,235,19,8}）为例：
  逐对算差，最小的一组是 |11 - 8| = 3 ✔

复杂度分析：
  时间 O(n*m)：每个数对都要算一次差
  空间 O(1)：只用了几个标量

解法二：两个数组排序 + 双指针收割【最优解】

官方解法。先把 a、b 各自升序排好，然后两个指针从头并进：算一次当前差的
绝对值，再让"指向较小值"的那个指针前进一格。理由是：若 a[i] < b[j]，
则 a[i] 与 b[j..] 中任何一个元素的差都不小于 a[i] 与 b[j] 的差（b 升序），
所以 a[i] 这个候选可以在这一步就彻底判死，换 a[i+1] 来试。

关键点：
  · 排序后最小差一定出现在"两数组元素交错处"，双指针只需单向推进，
    不会漏掉任何可能更优的组合
  · 每次只在 a[i] < b[j] 时推进 i，否则推进 j；两边相等时差为 0，
    已经是理论下界，直接结束
  · 差仍然是先扩宽类型再相减，理由同解法一：极值相减会溢出
  · sort 会改动传入的列表（力扣允许），调用方要保留原序时需自行拷贝

以示例（a = {1,3,15,11,2}，b = {23,127,235,19,8}）为例：
  排序后 a = [1,2,3,11,15]，b = [8,19,23,127,235]
  (1,8) 差 7 → 1 < 8，i 前进
  (2,8) 差 6 → i 前进
  (3,8) 差 5 → i 前进
  (11,8) 差 3 → 记录 3，11 > 8，j 前进
  (11,19) 差 8 → i 前进
  (15,19) 差 4 → j 前进
  (15,23) 差 8 → 15 < 23，i 前进到末尾，结束 → 答案 3 ✔

复杂度分析：
  时间 O(n log n + m log m)：两次排序，之后 O(n+m) 的双指针是低阶项
  空间 O(log n + log m)：排序栈开销；不额外申请数组
"""

INT_MIN = -2**31
INT_MAX = 2**31 - 1


class Solution1:
    def smallestDifference(self, a: list, b: list) -> int:
        if not a or not b:
            return 0

        best = None
        for x in a:
            for y in b:
                d = abs(x - y)
                if best is None or d < best:
                    best = d
        return best


class Solution2:
    def smallestDifference(self, a: list, b: list) -> int:
        if not a or not b:
            return 0

        a.sort()
        b.sort()

        i, j = 0, 0
        best = None
        while i < len(a) and j < len(b):
            d = abs(a[i] - b[j])
            if best is None or d < best:
                best = d

            # 0 是绝对下界，再往下走也只会得到不小于 0 的差值
            if best == 0:
                break

            # 小的一侧已经榨干：它和对面更靠后的元素只会更远
            if a[i] < b[j]:
                i += 1
            else:
                j += 1
        return best


# ===== 测试辅助 =====
def check(a: list, b: list, want: int) -> None:
    # 解法二会原地排序，两个解法各拿一份拷贝
    assert Solution1().smallestDifference(a[:], b[:]) == want
    assert Solution2().smallestDifference(a[:], b[:]) == want


if __name__ == "__main__":
    # 示例：最小差来自 (11, 8)，其余数对都比 3 大
    check([1, 3, 15, 11, 2], [23, 127, 235, 19, 8], 3)

    # 空数组：没有数对可比，按约定返回 0
    check([], [1, 2], 0)
    check([1, 2], [], 0)

    # 单元素：只能比这一对
    check([5], [7], 2)

    # 差为 0：两个数组有共同元素，此时应立刻结束
    check([1, 2, 3], [9, 3, 5], 0)

    # 差值溢出 32 位但答案合法：
    # |INT_MIN - INT_MAX| = 4294967295，|0 - INT_MAX| = 2147483647 才是答案
    check([INT_MIN, 0], [INT_MAX], INT_MAX)

    # 极值对撞：正确答案是 0，写错位宽会先算出负的差值再取绝对值
    check([INT_MAX, INT_MIN], [INT_MIN, INT_MAX], 0)

    # 两个数组各自内部有重复值时，双指针不能因为去重而少看候选
    check([7, 7, 7], [9, 9], 2)

    print("all tests passed")
