/*
============================================================================
面试题 05.06. 整数转换（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/convert-integer-lcci/
分类：位运算 · 异或 + 汉明重量

整数转换。编写一个函数，确定需要改变几个位才能将整数 A 转成整数 B。

示例 1：
输入：A = 29 （或者 0b11101）, B = 15（或者 0b01111）
输出：2

示例 2：
输入：A = 1，B = 2
输出：2

提示：
- A，B 范围在 [-2147483648, 2147483647] 之间
*/
#include <cassert>
#include <climits>
#include <iostream>
using namespace std;

/*
解法：异或 + n & (n - 1) 消去最低位的 1【最优解】

官方提示只给了一条路：想想异或表示什么。它同时也就是本题的最优解 ——
每个要翻转的位都必须被至少看一眼，O(k) 已是下界，O(1) 空间也已是下界。

为什么慢：最直观的做法是把 A、B 都展开成 32 位逐位比对，固定 32 轮；
而 32 轮里有几轮真的存在差异，完全取决于输入。A 与 B 相等时答案 0，
却照样比完 32 次。

换个角度：异或的结果本身就是一张「差异位图」—— 同一位相同则为 0、
不同则为 1。于是「改几个位」等价于「异或结果里有几个 1」，本题退化成
数 1 的个数，用 n &= n - 1 每轮抹掉一个 1 就够。

关键点：
  · A、B 都可能为负，异或必须在无符号域里做：先把两边都转成 unsigned，
    否则 d = A ^ B 为负时，任何右移都会补符号位，循环永远走不到 0
  · 终止条件只能是 d == 0，不能写 d > 0 再移位
  · 答案与「真值」无关，只看位：A = -1、B = 0 时 32 位全不同，答案是 32
  · 计数在清位之后，顺序反了会少算最后一次

手推一遍（A = 29，B = 15）：
  29 = 11101，15 = 01111
  11101 ^ 01111 = 10010 → 差异在第 1、4 位
  10010 & 10001 = 10000 → count = 1
  10000 & 01111 = 00000 → count = 2
  d == 0 结束 → 2 ✔

以 A = -1、B = 0 为例：
  -1 的 32 位补码是 32 个 1，与 0 异或后仍是 32 个 1
  每轮清掉一个 1，共 32 轮 → 32 ✔（若留在有符号域里右移，这里会死循环）

复杂度分析：
  时间 O(k)：k 为不同位的个数，最坏 32
  空间 O(1)：只用一个计数器
*/
class Solution
{
public:
    // 返回把 A 的若干位翻转后变成 B 所需的最少翻转次数
    int convertInteger(int A, int B)
    {
        // 两边都先转 unsigned：负数按 32 位补码参与异或，结果才是一张
        // 干净的差异位图，而不是带符号位的负数
        unsigned int d = static_cast<unsigned int>(A) ^
                         static_cast<unsigned int>(B);
        int count = 0;

        // d == 0 是唯一可靠的终止条件：清位必然把 32 位域清空
        while (d != 0)
        {
            d &= d - 1;
            ++count;
        }
        return count;
    }
};

namespace
{
void check(int A, int B, int want)
{
    Solution solution;
    assert(solution.convertInteger(A, B) == want);
}
} // namespace

int main()
{
    // 示例 1：差异在第 1、4 位
    check(29, 15, 2);

    // 示例 2：1 与 2 只有第 0、1 两位不同
    check(1, 2, 2);

    // 边界：两个负数，且完全相等，答案 0
    check(-1, -1, 0);

    // 边界：负数对 —— -1 的 32 位全是 1，与 0 相比 32 位全要翻转
    check(-1, 0, 32);
    check(0, -1, 32);

    // 边界：最小值与最大值，32 位全不同
    check(INT_MIN, INT_MAX, 32);

    // 边界：只差符号位（-1 与 2147483647）
    check(-1, INT_MAX, 1);

    // 边界：0 与 0
    check(0, 0, 0);

    cout << "all tests passed" << endl;
    return 0;
}
