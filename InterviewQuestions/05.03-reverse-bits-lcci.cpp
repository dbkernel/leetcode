/*
============================================================================
面试题 05.03. 翻转数位（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/reverse-bits-lcci/
分类：前缀后缀统计 · 位运算（连续 1 的段）

给定一个32位整数 num，你可以将一个数位从0变为1。请编写一个程序，找出你
能够获得的最长的一串1的长度。

示例 1：
输入: num = 1775(11011101111₂)
输出: 8

示例 2：
输入: num = 7(0111₂)
输出: 4
*/
#include <algorithm>
#include <cassert>
#include <iostream>
using namespace std;

/*
解法：按连续 1 的段拼接（prev / cur 双段计数）【最优解】

为什么慢：暴力做法是枚举「把哪一位从 0 翻成 1」，再逐位数一遍最长连续 1，
需要 32 次、每次 32 位，共 1024 步。位宽固定为 32，这算不上灾难，但每一位
都重扫一遍是把同一段连续 1 反复数了很多次 —— 翻某一位能带来多少收益，
只取决于它左右两侧各有多长的连续 1。

换个角度：把 num 看成 32 个格子，只关心「每段连续 1 有多长」。一次从低位
到高位扫描，用 cur 记当前正在延伸的 1 段长度，prev 记被一个 0 隔开的上一段
长度。走到某个 0 时，把它翻成 1 就能把两段接起来，长度正是 prev + cur + 1。

关键点：
  · 遇到 0 先交接再计数：prev = cur、cur = 0，候选值用交接前后的两段算
  · 候选值每一步都要更新（在 1 的位置上也更新），否则末尾那段 1 的收益
    要靠后面根本不存在的 0 才能被发现
  · 32 位全是 1 时公式会算出 33，必须把答案截到 32 —— 没有 0 可翻
  · 负数按无符号位模式处理：最高位是数据位，不能当作符号位跳过
  · 固定循环 32 次，不能写 while (num) —— 负数右移补 1，永远不会归零

手推一遍：
以 num = 1775（二进制 11011101111）为例，从低位往高位看是 1111 0 111 0 11：
  走过 4 个 1：cur = 4，候选 0 + 4 + 1 = 5
  遇到 0：prev = 4，cur = 0，候选 4 + 0 + 1 = 5
  走过 3 个 1：cur = 3，候选 4 + 3 + 1 = 8 ✔（翻掉中间那个 0）
  遇到 0：prev = 3，cur = 0，候选 4
  走过 2 个 1：cur = 2，候选 3 + 2 + 1 = 6
  答案 8 ✔

以 num = -1（32 位全 1）为例：
  cur 一路涨到 32，候选 0 + 32 + 1 = 33，被截成 32 ✔
以 num = 0 为例：
  第一个 0 就给出候选 0 + 0 + 1 = 1 ✔

复杂度分析：
  时间 O(1)：恒定 32 次迭代，与数值大小无关
  空间 O(1)：prev、cur、best 三个变量
*/

class Solution
{
public:
    int reverseBits(int num)
    {
        // 按无符号位模式处理，负数的最高位同样是可翻转的数据位
        unsigned int u = static_cast<unsigned int>(num);
        int prev = 0; // 上一段（与当前段之间隔着恰好一个 0）的长度
        int cur = 0;  // 当前正在延伸的 1 段长度
        int best = 0;

        for (int i = 0; i < 32; ++i)
        {
            if ((u & 1u) != 0)
            {
                ++cur;
            }
            else
            {
                // 这一段到此为止，它变成下一段的「上一段」
                prev = cur;
                cur = 0;
            }
            // 把脚下这一位翻成 1 能拼出的长度；在 1 上也算，覆盖末尾段
            best = max(best, prev + cur + 1);
            u >>= 1;
        }

        // 全 1 时没有任何 0 可翻，答案不能超过位宽
        return min(best, 32);
    }
};

int main()
{
    Solution s;

    // 示例 1：中间那个 0 两侧各有一段 1，拼起来最长
    assert(s.reverseBits(1775) == 8);

    // 示例 2：只有一个 1 段（且高位还有 0 可翻），整段加一位
    assert(s.reverseBits(7) == 4);

    // 边界：num = 0，翻出一位 1
    assert(s.reverseBits(0) == 1);

    // 边界：-1 的 32 位全是 1，没有可翻的 0，答案必须是 32 而不是 33
    assert(s.reverseBits(-1) == 32);

    // 边界：只有一位 1
    assert(s.reverseBits(1) == 2);
    assert(s.reverseBits(2) == 2);

    // 反直觉：低位连续 1 的段彼此独立，翻转只能合并相邻两段
    assert(s.reverseBits(5) == 3);          // 101
    assert(s.reverseBits(683) == 4);        // 1010101011

    // 边界：10 个连续 1，前端再翻一位
    assert(s.reverseBits(1023) == 11);

    // 反直觉：奇偶位交替时，任意 0 两侧都只有单 1，答案 3
    assert(s.reverseBits(1431655765) == 3);  // 0101...0101
    assert(s.reverseBits(-1431655766) == 3); // 1010...1010

    // 边界：负数最高位为 1，不能被当成符号位忽略
    assert(s.reverseBits(-2147483648) == 2); // 只有最高位是 1

    // 边界：INT_MAX，32 位全 1
    assert(s.reverseBits(2147483647) == 32);

    cout << "all tests passed" << endl;
    return 0;
}
