struct Solution;

/*
解法：逐位扫描 + 拼接前越界预判【最优解】

官方题解只给出这一种方法，它同时也就是本题的最优解：只扫一遍，时间 O(N)
已是下界；除几个计数变量外不需要额外空间。

为什么慢：最直接的想法是「先把数字子串截出来，再交给标准库的 parse 转整数」。
问题在于超长数字串（200 位）根本放不进任何整型，parse 只会返回 Err；
而用 i64/i128 兜底也只是把边界往后推，遇到更长输入照样失效。

换个角度：既然全串可能远超 i32 范围，就别等到算完再判，而是在「这一步
拼接会不会越界」之前就拦住。设 res 是已经拼好的部分，x 是待拼的当前位，
阈值 bndry = i32::MAX / 10 = 214748364，则只有两种越界：
  · res > bndry          → 10 * res 本身就已经 ≥ 2147483650
  · res == bndry 且 x > 7 → 拼接结果 ≥ 2147483648
两种情况都直接返回带符号的边界值，剩下的循环不必再跑。

关键点：
  · 只跳过前导空格；一旦进入数字或符号，后面再遇空格必须停止，不能继续跳
  · 有符号位才把 i 推到 1，无符号位时 i 停在 0，否则会漏读第一位数字
  · 符号必须在「返回边界值」时一起生效，否则 "-91283472332" 会返回正数
  · '-' 和 '+' 之后必须紧跟数字，否则结果为 0（例如 "+-12"、"  + 413"）
  · 前导零不需要特殊处理，"0032" 自然拼成 32

Rust 的一处写法细节：
  · res 用 i32 而不是 i64，配合 bndry 预判 —— 这样才真正复现题目要求的
    「环境只能存储 32 位有符号整数」这一限制
  · 逐字节处理，本题限定 ASCII

以 s = "   -42" 为例：
  跳过 3 个前导空格，i 停在 '-'
  sign = -1，i 后移一位
  读 '4'：res = 4；读 '2'：res = 42
  字符串结束，返回 -1 * 42 = -42

以 s = "-91283472332" 为例：
  拼到 res = 214748364 时，下一位是 '7'，还没越界（等于 bndry 且不大于 7）
  再拼一位后 res = 2147483647，此时下一位 '2'：res > bndry → 立刻返回
  i32::MIN = -2147483648

复杂度分析：
  时间 O(N)：最多扫一遍，越界时提前退出
  空间 O(1)：只用 res、符号、下标几个变量
*/
impl Solution {
    pub fn my_atoi(s: String) -> i32 {
        let int_max = i32::MAX;
        let int_min = i32::MIN;
        // 拼接阈值：i32::MAX / 10，用来在乘 10 之前判断是否越界
        let bndry = i32::MAX / 10;

        let bytes = s.as_bytes();
        let n = bytes.len();
        let mut i = 0usize;

        // 只跳前导空格；进入数字区后再遇空格必须停，不能继续跳
        while i < n && bytes[i] == b' ' {
            i += 1;
        }

        let mut sign = 1i32;
        if i < n && bytes[i] == b'-' {
            sign = -1;
            i += 1;
        } else if i < n && bytes[i] == b'+' {
            // 正号也要吃掉，否则会把 '+' 当成非数字字符直接返回 0
            i += 1;
        }

        let mut res = 0i32;
        while i < n && bytes[i].is_ascii_digit() {
            let x = (bytes[i] - b'0') as i32;

            // 先判越界再拼接，避免 10 * res 本身就已经溢出
            if res > bndry || (res == bndry && x > 7) {
                return if sign == 1 { int_max } else { int_min };
            }

            res = 10 * res + x;
            i += 1;
        }

        // 符号必须在这里统一生效，循环里 res 始终保持非负
        sign * res
    }
}

// ---- 以下为自测代码，不属于题解主体 ----

// 一个用例 = 输入 + 期望输出
fn check(s: &str, want: i32) {
    let got = Solution::my_atoi(s.to_string());
    assert_eq!(got, want, "my_atoi({:?}) = {}, want {}", s, got, want);
}

fn main() {
    // 示例 1：无符号位、无空格
    check("42", 42);

    // 示例 2：前导空格 + 负号
    check("   -42", -42);

    // 示例 3：数字之后跟着非数字，其余部分忽略
    check("4193 with words", 4193);

    // 边界：以字母开头，一个数字都读不到
    check("words and 987", 0);

    // 边界：空串与纯空格，必须返回 0 而不是越界
    check("", 0);
    check("     ", 0);

    // 边界：只有符号位，没有数字
    check("+", 0);
    check("-", 0);
    check("+-12", 0);

    // 边界：正号后紧跟数字，验证 '+' 被正确吃掉
    check("+1", 1);

    // 边界：符号位与数字之间有空格，属于「紧跟」规则之外，应返回 0
    check("  + 413", 0);

    // 边界：前导零不影响结果
    check("0032", 32);
    check("00000-42a1234", 0);

    // 上溢：2147483648 应截断为 i32::MAX
    check("2147483648", i32::MAX);

    // 下溢：比 i32::MIN 绝对值更大的负数应截断为 i32::MIN
    check("-91283472332", i32::MIN);

    // 边界：恰好等于上下界的两个值必须原样返回，不能被误判为越界
    check("2147483647", i32::MAX);
    check("-2147483648", i32::MIN);

    // 边界：比上界小 1，验证 bndry 判定没有提前一位
    check("2147483646", 2147483646);

    println!("all tests passed");
}
