/*
============================================================================
LCR 192 / 剑指 Offer 67. 把字符串转换成整数 (atoi)（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/ba-zi-fu-chuan-zhuan-huan-cheng-zheng-shu-lcof/
分类：字符串 · 状态机（逐位拼接 + 越界预判）

说明：本题在 leetcode.cn 上现名「把字符串转换成整数 (atoi)」，函数名为
myAtoi（参数名改为 s）。本质与主站 8 题一致。
============================================================================

请你来实现一个 myAtoi(string s) 函数，使其能将字符串转换成一个 32 位有符号
整数（类似 C/C++ 中的 atoi 函数）。

函数 myAtoi(string s) 的算法如下：
- 读入字符串并丢弃无用的前导空格
- 检查下一个字符（假设还未到字符末尾）为正还是负号，读取该字符（如果有）。
  确定最终结果是负数还是正数。如果两者都不存在，则假定结果为正。
- 读入下一个字符，直到到达下一个非数字字符或到达输入的结尾。字符串的其余
  部分将被忽略。
- 将前面步骤读入的这些数字转换为整数（即，"123" -> 123，"0032" -> 32）。
  如果没有读入数字，则整数为 0。必要时更改符号（从步骤 2 开始）。
- 如果整数数超过 32 位有符号整数范围 [-2^31, 2^31 - 1]，需要截断这个整数，
  使其保持在这个范围内。具体来说，小于 -2^31 的整数应该被固定为 -2^31，
  大于 2^31 - 1 的整数应该被固定为 2^31 - 1。
- 返回整数作为最终结果。

注意：
- 本题中的空白字符只包括空格字符 ' '。
- 除前导空格或数字后的其余字符串外，请勿忽略 任何其他字符。

示例 1：
输入：s = "42"
输出：42

示例 2：
输入：s = "   -42"
输出：-42

示例 3：
输入：s = "4193 with words"
输出：4193

提示：
0 <= s.length <= 200
s 由英文字母（大写和小写）、数字（0-9）、' '、'+'、'-' 和 '.' 组成

注意：
本题与主站 8 题相同：https://leetcode.cn/problems/string-to-integer-atoi/
*/
package main

import (
	"fmt"
	"math"
)

/*
解法：逐位扫描 + 拼接前越界预判【最优解】

官方题解只给出这一种方法，它同时也就是本题的最优解：只扫一遍，时间 O(N)
已是下界；除几个计数变量外不需要额外空间。

为什么慢：最直接的想法是「先把数字子串截出来，再交给 strconv.Atoi 转整数」。
问题在于超长数字串（200 位）根本放不进任何整型，Atoi 会直接返回错误值；
而用 int64 兜底也只是把边界往后推，遇到更长输入照样失效。

换个角度：既然全串可能远超 int32 范围，就别等到算完再判，而是在「这一步
拼接会不会越界」之前就拦住。设 res 是已经拼好的部分，x 是待拼的当前位，
阈值 bndry = MaxInt32 / 10 = 214748364，则只有两种越界：
  · res > bndry          → 10 * res 本身就已经 ≥ 2147483650
  · res == bndry 且 x > 7 → 拼接结果 ≥ 2147483648
两种情况都直接返回带符号的边界值，剩下的循环不必再跑。

关键点：
  · 只跳过前导空格；一旦进入数字或符号，后面再遇空格必须停止，不能继续跳
  · 有符号位才把 i 推到 1，无符号位时 i 停在 0，否则会漏读第一位数字
  · 符号必须在「返回边界值」时一起生效，否则 "-91283472332" 会返回正数
  · '-' 和 '+' 之后必须紧跟数字，否则结果为 0（例如 "+-12"、"  + 413"）
  · 前导零不需要特殊处理，"0032" 自然拼成 32

Go 的一处写法说明：
  · 与官方一致，res 始终是非负的 int32 量级，靠 bndry 预判拦越界，
    全程不依赖平台 int 的位宽（Go 的 int 在 64 位机器上是 64 位，
    直接用 int 累加反而会掩盖溢出问题）
  · 用 math.MaxInt32 / math.MinInt32 表达边界，避免手写常量

以 s = "   -42" 为例：
  跳过 3 个前导空格，i 停在 '-'
  sign = -1，i 后移一位
  读 '4'：res = 4；读 '2'：res = 42
  字符串结束，返回 -1 * 42 = -42

以 s = "-91283472332" 为例：
  sign = -1，res 一路累加到 91283472332（int64 装得下）
  结束时 res > MaxInt32 且为负号 → 返回 MinInt32 = -2147483648

复杂度分析：
  时间 O(N)：最多扫一遍
  空间 O(1)：只用 res、符号、下标几个变量
*/

// 把字符串转换成 32 位有符号整数，超出范围则截断
func myAtoi(s string) int {
	const (
		intMax = math.MaxInt32
		intMin = math.MinInt32
	)

	i := 0
	// 只跳前导空格；进入数字区后再遇空格必须停，不能继续跳
	for i < len(s) && s[i] == ' ' {
		i++
	}

	sign := 1
	if i < len(s) && s[i] == '-' {
		sign = -1
		i++
	} else if i < len(s) && s[i] == '+' {
		// 正号也要吃掉，否则会把 '+' 当成非数字字符直接返回 0
		i++
	}

	var res int
	bndry := int(intMax / 10)

	for i < len(s) && s[i] >= '0' && s[i] <= '9' {
		x := int(s[i] - '0')

		// 先判越界再拼接，避免 10 * res 本身就已经溢出
		if res > bndry || (res == bndry && x > 7) {
			if sign == 1 {
				return intMax
			}
			return intMin
		}

		res = 10*res + x
		i++
	}

	// 符号必须在这里统一生效，循环里 res 始终保持非负
	return sign * res
}

// ---- 以下为自测代码，不属于题解主体 ----

// 一个用例 = 输入 + 期望输出
func check(s string, want int) {
	if got := myAtoi(s); got != want {
		panic(fmt.Sprintf("myAtoi(%q) = %d, want %d", s, got, want))
	}
}

func main() {
	// 示例 1：无符号位、无空格
	check("42", 42)

	// 示例 2：前导空格 + 负号
	check("   -42", -42)

	// 示例 3：数字之后跟着非数字，其余部分忽略
	check("4193 with words", 4193)

	// 边界：以字母开头，一个数字都读不到
	check("words and 987", 0)

	// 边界：空串与纯空格，必须返回 0 而不是越界
	check("", 0)
	check("     ", 0)

	// 边界：只有符号位，没有数字
	check("+", 0)
	check("-", 0)
	check("+-12", 0)

	// 边界：正号后紧跟数字，验证 '+' 被正确吃掉
	check("+1", 1)

	// 边界：符号位与数字之间有空格，属于「紧跟」规则之外，应返回 0
	check("  + 413", 0)

	// 边界：前导零不影响结果
	check("0032", 32)
	check("00000-42a1234", 0)

	// 上溢：2147483648 应截断为 MaxInt32
	check("2147483648", math.MaxInt32)

	// 下溢：比 MinInt32 绝对值更大的负数应截断为 MinInt32
	check("-91283472332", math.MinInt32)

	// 边界：恰好等于上下界的两个值必须原样返回，不能被误判为越界
	check("2147483647", math.MaxInt32)
	check("-2147483648", math.MinInt32)

	// 边界：比上界小 1，验证没有提前一位截断
	check("2147483646", 2147483646)

	fmt.Println("all tests passed")
}
