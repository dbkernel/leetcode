/*
解法一：逐位检查（固定 32 轮）【非最优】

为什么慢：循环次数被写死成位宽 —— 输入 11 只含 3 个 1，也要老老实实转满
32 轮；输入 0 更是白跑 32 次。代价与「答案有多大」完全脱钩。

换个角度：题目问的是 1 的个数，那么值得处理的只有 1 所在的那几位。让每一
轮至少消耗掉一个 1，轮数自然就等于答案本身。

关键点：
  · 轮数是位宽 32，与 n 的取值无关，这正是它慢的根源
  · 掩码用 1u32 << bit：字面量显式带类型，天然不会溢出到符号位
  · 形参是 i32，先 `as u32` 转成无符号再参与移位，语义才与题目的 32 位
    位图一致

手推一遍（n = 11，0b1011）：
  第 0 位：1011 & 0001 ≠ 0 → count = 1
  第 1 位：1011 & 0010 ≠ 0 → count = 2
  第 2 位：1011 & 0100 = 0
  第 3 位：1011 & 1000 ≠ 0 → count = 3
  第 4 到 31 位全为 0，跑满 32 轮 → 3 ✔

复杂度分析：
  时间 O(w)：w 固定为 32，与 1 的个数无关
  空间 O(1)：只用一个计数器

解法二：n & (n - 1) 消去最低位的 1【最优解】

为什么慢：解法一每轮只回答「这一位是不是 1」，32 轮里绝大多数是白问。
如果能每轮直接抹掉一个 1，轮数就等于答案。

换个角度：n - 1 会把最低位的 1 翻成 0，并把它右边的 0 全部翻成 1；再与 n
相与，恰好只清掉那一个最低位的 1，更高位一位不动。于是每做一次
n &= n - 1，1 的个数就少一个，做几次就能数出几个。

关键点：
  · 终止条件是 u == 0，不能留 in i32 里判 u > 0 再移位 —— 补码下负数
    永远不为 0，算术右移就是死循环
  · u 声明为 u32，让清位与计数都落在 32 位域内
  · 计数动作发生在清位之后，顺序反了会少算最后一次

手推一遍（n = 11，0b1011）：
  1011 & 1010 = 1010 → count = 1
  1010 & 1001 = 1000 → count = 2
  1000 & 0111 = 0000 → count = 3
  u 变成 0 结束 → 3 ✔（只转了 3 轮，正好等于 1 的个数）

复杂度分析：
  时间 O(k)：k 为 1 的个数，最坏（32 位全 1）k = 32
  空间 O(1)：只用一个计数器

解法三：内置 popcount【最优解，与解法二并列】

这一条不是「更慢」，而是把数 1 的动作交给标准库：u32::count_ones 在支持
POPCNT 的机器上编译成一条指令，否则也是常数条位运算。

换个角度：汉明重量是处理器直接支持的度量，没必要在源码里重写一遍。

关键点：
  · 方法挂在 u32 上而不是 i32 上：i32 没有 count_ones，必须先 `as u32`
  · 返回值是 u32，题目要 i32，再用 `as i32` 收口（本题至多 32，不会截断）
  · 面试通常要求手写解法二，内置函数只作为工程上的捷径

手推一遍（n = 11）：
  (11i32 as u32).count_ones() → 3 ✔

复杂度分析：
  时间 O(1)：单条指令，或常数条位运算
  空间 O(1)
*/
impl Solution1 {
    pub fn hamming_weight(n: i32) -> i32 {
        let u = n as u32;
        let mut count = 0;

        for bit in 0..32 {
            // 字面量带 u32 后缀：掩码不会因为符号位而出现歧义
            if u & (1u32 << bit) != 0 {
                count += 1;
            }
        }
        count
    }
}

impl Solution2 {
    pub fn hamming_weight(n: i32) -> i32 {
        let mut u = n as u32;
        let mut count = 0;

        // u == 0 是唯一可靠的终止条件：清位一定会把 32 位域清空
        while u != 0 {
            u &= u - 1;
            count += 1;
        }
        count
    }
}

impl Solution3 {
    pub fn hamming_weight(n: i32) -> i32 {
        (n as u32).count_ones() as i32
    }
}

