/*
============================================================================
191. 位 1 的个数（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/number-of-1-bits/
分类：位运算 · 汉明重量（n & (n - 1)）

给定一个正整数 n，编写一个函数，获取一个正整数的二进制形式并返回其二进制
表达式中 设置位 的个数（也被称为 汉明重量）。

示例 1：
输入：n = 11
输出：3
解释：输入的二进制串 1011 中，共有 3 个设置位。

示例 2：
输入：n = 128
输出：1
解释：输入的二进制串 10000000 中，共有 1 个设置位。

示例 3：
输入：n = 2147483645
输出：30
解释：输入的二进制串 1111111111111111111111111111101 中，共有 30 个设置位。

提示：
- 1 <= n <= 2^31 - 1

进阶：如果多次调用这个函数，你将如何优化你的算法？
*/
#include <cassert>
#include <iostream>
using namespace std;

/*
解法一：逐位检查（固定 32 轮）【非最优】

为什么慢：循环次数被写死成位宽 —— 输入 11 只含 3 个 1，也要老老实实转满
32 轮；输入 0 更是白跑 32 次。代价与「答案有多大」完全脱钩。

换个角度：题目问的是 1 的个数，那么值得处理的只有 1 所在的那几位。让每一
轮至少消耗掉一个 1，轮数自然就等于答案本身。

关键点：
  · 轮数是位宽 32，与 n 的取值无关，这正是它慢的根源
  · 掩码必须写成 1u：1 << 31 在 int 上是有符号溢出，属未定义行为
  · 平台签名的形参是 int，负数在这里按 32 位补码看待，所以先转无符号再
    参与移位，否则算术右移会补符号位

手推一遍（n = 11，0b1011）：
  第 0 位：1011 & 0001 ≠ 0 → count = 1
  第 1 位：1011 & 0010 ≠ 0 → count = 2
  第 2 位：1011 & 0100 = 0
  第 3 位：1011 & 1000 ≠ 0 → count = 3
  第 4 到 31 位全为 0，跑满 32 轮 → 3 ✔

复杂度分析：
  时间 O(w)：w 固定为 32，与 1 的个数无关
  空间 O(1)：只用一个计数器

解法二：n & (n - 1) 消去最低位的 1【最优解】

为什么慢：解法一每轮只回答「这一位是不是 1」，32 轮里绝大多数是白问。
如果能每轮直接抹掉一个 1，轮数就等于答案。

换个角度：n - 1 会把最低位的 1 翻成 0，并把它右边的 0 全部翻成 1；再与 n
相与，恰好只清掉那一个最低位的 1，更高位一位不动。于是每做一次
n &= n - 1，1 的个数就少一个，做几次就能数出几个。

关键点：
  · 终止条件是 n == 0，不能写成 n > 0 之后再做移位 —— 补码下负数永远
    不为 0，配合算术右移就是死循环
  · 先转成无符号再进循环，让「清位」与「移位」都落在 32 位域里，不依赖
    编译器的实现定义行为
  · 计数动作发生在清位之后，顺序反了会少算最后一次

手推一遍（n = 11，0b1011）：
  1011 & 1010 = 1010 → count = 1
  1010 & 1001 = 1000 → count = 2
  1000 & 0111 = 0000 → count = 3
  n 变成 0 结束 → 3 ✔（只转了 3 轮，正好等于 1 的个数）

复杂度分析：
  时间 O(k)：k 为 1 的个数，最坏（32 位全 1）k = 32
  空间 O(1)：只用一个计数器

解法三：内置 popcount【最优解，与解法二并列】

这一条不是「更慢」，而是把数 1 的动作交给编译器内建函数：目标机器有
POPCNT 指令时就是一条汇编，没有时编译器也会展开成常数条位运算。

换个角度：汉明重量是处理器直接支持的度量，没必要在源码里重写一遍。

关键点：
  · 入参必须是定长无符号类型（unsigned / uint32 / u32），否则符号位会被
    当成普通的一位计入
  · 三种语言的入口不同：C++ 用 __builtin_popcount，Go 用
    bits.OnesCount32，Python 用 bin(n).count("1")，Rust 用
    u32::count_ones
  · 面试通常要求手写解法二，内置函数只作为工程上的捷径

手推一遍（n = 11）：
  __builtin_popcount(11) → 3 ✔

复杂度分析：
  时间 O(1)：单条指令，或编译器展开的常数条指令
  空间 O(1)
*/
class Solution1
{
public:
    int hammingWeight(int n)
    {
        // 先转无符号：形参是有符号 int，后续任何右移都会被要求补符号位
        unsigned int u = static_cast<unsigned int>(n);
        int count = 0;

        for (int bit = 0; bit < 32; ++bit)
        {
            // 1u 而不是 1：1 << 31 会让 int 溢出，属于未定义行为
            if ((u & (1u << bit)) != 0) ++count;
        }
        return count;
    }
};

class Solution2
{
public:
    int hammingWeight(int n)
    {
        unsigned int u = static_cast<unsigned int>(n);
        int count = 0;

        // u == 0 是唯一可靠的终止条件：清位一定会把 32 位域清空
        while (u != 0)
        {
            u &= u - 1;
            ++count;
        }
        return count;
    }
};

class Solution3
{
public:
    int hammingWeight(int n)
    {
        // 显式转无符号：popcount 对负数按补码数位，语义容易和题面混淆
        return __builtin_popcount(static_cast<unsigned int>(n));
    }
};

namespace
{
void check(int n, int want)
{
    Solution1 s1;
    Solution2 s2;
    Solution3 s3;

    assert(s1.hammingWeight(n) == want);
    assert(s2.hammingWeight(n) == want);
    assert(s3.hammingWeight(n) == want);
}
} // namespace

int main()
{
    // 示例 1：三个 1 分散在低位
    check(11, 3);

    // 示例 2：只有一个 1，最适合暴露「轮数写死」与「轮数等于答案」的差别
    check(128, 1);

    // 示例 3：30 个 1，接近最坏情况
    check(2147483645, 30);

    // 边界：0，任何一位都不能被算进去
    check(0, 0);

    // 边界：32 位全 1（按 32 位补码即 -1），答案是被写死的 32
    check(static_cast<int>(0xFFFFFFFFu), 32);

    cout << "all tests passed" << endl;
    return 0;
}
