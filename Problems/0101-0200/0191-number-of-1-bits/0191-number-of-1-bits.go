/*
============================================================================
191. 位 1 的个数（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/number-of-1-bits/
分类：位运算 · 汉明重量（n & (n - 1)）

给定一个正整数 n，编写一个函数，获取一个正整数的二进制形式并返回其二进制
表达式中 设置位 的个数（也被称为 汉明重量）。

示例 1：
输入：n = 11
输出：3
解释：输入的二进制串 1011 中，共有 3 个设置位。

示例 2：
输入：n = 128
输出：1
解释：输入的二进制串 10000000 中，共有 1 个设置位。

示例 3：
输入：n = 2147483645
输出：30
解释：输入的二进制串 1111111111111111111111111111101 中，共有 30 个设置位。

提示：
- 1 <= n <= 2^31 - 1

进阶：如果多次调用这个函数，你将如何优化你的算法？
*/
package main

import (
	"fmt"
	"math/bits"
)

/*
解法一：逐位检查（固定 32 轮）【非最优】

为什么慢：循环次数被写死成位宽 —— 输入 11 只含 3 个 1，也要老老实实转满
32 轮；输入 0 更是白跑 32 次。代价与「答案有多大」完全脱钩。

换个角度：题目问的是 1 的个数，那么值得处理的只有 1 所在的那几位。让每一
轮至少消耗掉一个 1，轮数自然就等于答案本身。

关键点：
  · 轮数是位宽 32，与 n 的取值无关，这正是它慢的根源
  · 掩码用 uint32(1) << bit，别写 1 << 31 —— Go 里常量 1 是无类型的，
    与 int 结合时会变成 64 位 int，掩码位宽就跑偏了
  · 形参是 int（本机 64 位），先 uint32(n) 截到 32 位，语义才与题目一致

手推一遍（n = 11，0b1011）：
  第 0 位：1011 & 0001 ≠ 0 → count = 1
  第 1 位：1011 & 0010 ≠ 0 → count = 2
  第 2 位：1011 & 0100 = 0
  第 3 位：1011 & 1000 ≠ 0 → count = 3
  第 4 到 31 位全为 0，跑满 32 轮 → 3 ✔

复杂度分析：
  时间 O(w)：w 固定为 32，与 1 的个数无关
  空间 O(1)：只用一个计数器

解法二：n & (n - 1) 消去最低位的 1【最优解】

为什么慢：解法一每轮只回答「这一位是不是 1」，32 轮里绝大多数是白问。
如果能每轮直接抹掉一个 1，轮数就等于答案。

换个角度：n - 1 会把最低位的 1 翻成 0，并把它右边的 0 全部翻成 1；再与 n
相与，恰好只清掉那一个最低位的 1，更高位一位不动。于是每做一次
n &= n - 1，1 的个数就少一个，做几次就能数出几个。

关键点：
  · 终止条件是 u == 0，不能写 u > 0 之后再做移位 —— 若留在有符号域里，
    负数永远不为 0，配合算术右移就是死循环
  · u 用 uint32 承接，清位与计数都落在 32 位域内，与题目口径一致
  · 计数动作发生在清位之后，顺序反了会少算最后一次

手推一遍（n = 11，0b1011）：
  1011 & 1010 = 1010 → count = 1
  1010 & 1001 = 1000 → count = 2
  1000 & 0111 = 0000 → count = 3
  u 变成 0 结束 → 3 ✔（只转了 3 轮，正好等于 1 的个数）

复杂度分析：
  时间 O(k)：k 为 1 的个数，最坏（32 位全 1）k = 32
  空间 O(1)：只用一个计数器

解法三：内置 popcount【最优解，与解法二并列】

这一条不是「更慢」，而是把数 1 的动作交给标准库：math/bits 的
OnesCount32 在支持 POPCNT 的机器上编译成一条指令，否则也是常数条位运算。

换个角度：汉明重量是处理器直接支持的度量，没必要在源码里重写一遍。

关键点：
  · 必须选带位宽的版本 OnesCount32，不能用 OnesCount —— 后者按 int 的
    机器字长（64 位）数位，高位全 0 时结果虽然相同，语义却不对
  · 入参先 uint32(n)，保证只数低 32 位
  · 面试通常要求手写解法二，内置函数只作为工程上的捷径

手推一遍（n = 11）：
  bits.OnesCount32(11) → 3 ✔

复杂度分析：
  时间 O(1)：单条指令，或常数条位运算
  空间 O(1)
*/

// 解法一：逐位检查
func hammingWeight(n int) int {
	u := uint32(n)
	count := 0
	for bit := 0; bit < 32; bit++ {
		if u&(uint32(1)<<uint(bit)) != 0 {
			count++
		}
	}
	return count
}

// 解法二：n & (n-1) 消去最低位的 1
func hammingWeightClearLowest(n int) int {
	u := uint32(n)
	count := 0
	for u != 0 {
		u &= u - 1
		count++
	}
	return count
}

// 解法三：标准库 popcount
func hammingWeightBuiltin(n int) int {
	return bits.OnesCount32(uint32(n))
}

// ---- 以下为自测代码，不属于题解主体 ----

func check(n, want int) {
	if got := hammingWeight(n); got != want {
		panic(fmt.Sprintf("shift(%d) = %d, want %d", n, got, want))
	}
	if got := hammingWeightClearLowest(n); got != want {
		panic(fmt.Sprintf("clearLowest(%d) = %d, want %d", n, got, want))
	}
	if got := hammingWeightBuiltin(n); got != want {
		panic(fmt.Sprintf("builtin(%d) = %d, want %d", n, got, want))
	}
}

func main() {
	// 示例 1：三个 1 分散在低位
	check(11, 3)

	// 示例 2：只有一个 1，最适合暴露「轮数写死」与「轮数等于答案」的差别
	check(128, 1)

	// 示例 3：30 个 1，接近最坏情况
	check(2147483645, 30)

	// 边界：0，任何一位都不能被算进去
	check(0, 0)

	// 边界：32 位全 1（按 32 位补码即 -1），答案是被写死的 32
	check(-1, 32)
	check(0xFFFFFFFF, 32)

	fmt.Println("all tests passed")
}
