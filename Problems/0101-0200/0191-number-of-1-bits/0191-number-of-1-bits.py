"""
============================================================================
191. 位 1 的个数（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/number-of-1-bits/
分类：位运算 · 汉明重量（n & (n - 1)）

给定一个正整数 n，编写一个函数，获取一个正整数的二进制形式并返回其二进制
表达式中 设置位 的个数（也被称为 汉明重量）。

示例 1：
输入：n = 11
输出：3
解释：输入的二进制串 1011 中，共有 3 个设置位。

示例 2：
输入：n = 128
输出：1
解释：输入的二进制串 10000000 中，共有 1 个设置位。

示例 3：
输入：n = 2147483645
输出：30
解释：输入的二进制串 1111111111111111111111111111101 中，共有 30 个设置位。

提示：
- 1 <= n <= 2^31 - 1

进阶：如果多次调用这个函数，你将如何优化你的算法？
"""


"""
解法一：逐位检查（固定 32 轮）【非最优】

为什么慢：循环次数被写死成位宽 —— 输入 11 只含 3 个 1，也要老老实实转满
32 轮；输入 0 更是白跑 32 次。代价与「答案有多大」完全脱钩。

换个角度：题目问的是 1 的个数，那么值得处理的只有 1 所在的那几位。让每一
轮至少消耗掉一个 1，轮数自然就等于答案本身。

关键点：
  · 轮数是位宽 32，与 n 的取值无关，这正是它慢的根源
  · 掩码用 1 << bit 后与 n 相与：Python 的整数没有位宽，靠上面的循环上界
    32 把考察范围钉死在题目的 32 位域内
  · 不要用 while n > 0 配右移收尾，那样轮数取决于最高位在哪，与答案仍
    无关，且会让人误以为是解法二

手推一遍（n = 11，0b1011）：
  第 0 位：1011 & 0001 ≠ 0 → count = 1
  第 1 位：1011 & 0010 ≠ 0 → count = 2
  第 2 位：1011 & 0100 = 0
  第 3 位：1011 & 1000 ≠ 0 → count = 3
  第 4 到 31 位全为 0，跑满 32 轮 → 3 ✔

复杂度分析：
  时间 O(w)：w 固定为 32，与 1 的个数无关
  空间 O(1)：只用一个计数器

解法二：n & (n - 1) 消去最低位的 1【最优解】

为什么慢：解法一每轮只回答「这一位是不是 1」，32 轮里绝大多数是白问。
如果能每轮直接抹掉一个 1，轮数就等于答案。

换个角度：n - 1 会把最低位的 1 翻成 0，并把它右边的 0 全部翻成 1；再与 n
相与，恰好只清掉那一个最低位的 1，更高位一位不动。于是每做一次
n &= n - 1，1 的个数就少一个，做几次就能数出几个。

关键点：
  · 终止条件是 n == 0，清位一定会走到 0，不存在死循环
  · Python 的整数是任意精度，没有补码溢出问题：本题 n 为正，结果与
    C++/Go/Rust 完全一致
  · 计数动作发生在清位之后，顺序反了会少算最后一次

手推一遍（n = 11，0b1011）：
  1011 & 1010 = 1010 → count = 1
  1010 & 1001 = 1000 → count = 2
  1000 & 0111 = 0000 → count = 3
  n 变成 0 结束 → 3 ✔（只转了 3 轮，正好等于 1 的个数）

复杂度分析：
  时间 O(k)：k 为 1 的个数，最坏（32 位全 1）k = 32
  空间 O(1)：只用一个计数器

解法三：内置 popcount【最优解，与解法二并列】

这一条不是「更慢」，而是把数 1 的动作交给内建能力：bin 转成字符串后统计
字符 "1" 的个数，实际由 C 层一次扫描完成。

换个角度：汉明重量是内建支持的度量，没必要在源码里重写一遍。

关键点：
  · 用 bin(n).count("1")，不要用 len(bin(n)) - bin(n).rfind("1") 这类
    字符串切片技巧，后者在 n = 0 时会算成 1
  · 结果的位数由 n 自身决定，本题 n 为正，最高位不会补出多余的 1
  · 面试通常要求手写解法二，内置函数只作为工程上的捷径

手推一遍（n = 11）：
  bin(11) = "0b1011"，数 "1" 得 3 ✔

复杂度分析：
  时间 O(w)：扫描 w 位二进制串，w 固定为 32
  空间 O(w)：临时字符串，w 固定为 32
"""


class Solution1:
    def hammingWeight(self, n: int) -> int:
        count = 0
        for bit in range(32):
            if n & (1 << bit):
                count += 1
        return count


class Solution2:
    def hammingWeight(self, n: int) -> int:
        count = 0
        # 清位一定能把 32 位域清空，所以 n == 0 是可靠的终止条件
        while n:
            n &= n - 1
            count += 1
        return count


class Solution3:
    def hammingWeight(self, n: int) -> int:
        return bin(n).count("1")


def check(n: int, want: int) -> None:
    assert Solution1().hammingWeight(n) == want
    assert Solution2().hammingWeight(n) == want
    assert Solution3().hammingWeight(n) == want


if __name__ == "__main__":
    # 示例 1：三个 1 分散在低位
    check(11, 3)

    # 示例 2：只有一个 1，最适合暴露「轮数写死」与「轮数等于答案」的差别
    check(128, 1)

    # 示例 3：30 个 1，接近最坏情况
    check(2147483645, 30)

    # 边界：0，任何一位都不能被算进去
    check(0, 0)

    # 边界：32 位全 1，答案是被写死的 32
    check(0xFFFFFFFF, 32)

    print("all tests passed")
