/*
============================================================================
198. 打家劫舍（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/house-robber/
分类：动态规划 · 线性递推（相邻约束）

你是一个专业的小偷，计划偷窃沿街的房屋。每间房内都藏有一定的现金，影响你偷窃的唯一制约因素就是相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。

给定一个代表每个房屋存放金额的非负整数数组，计算你 不触动警报装置的情况下 ，一夜之内能够偷窃到的最高金额。

示例 1：
输入：[1,2,3,1]
输出：4
解释：偷窃 1 号房屋 (金额 = 1) ，然后偷窃 3 号房屋 (金额 = 3)。
     偷窃到的最高金额 = 1 + 3 = 4 。

示例 2：
输入：[2,7,9,3,1]
输出：12
解释：偷窃 1 号房屋 (金额 = 2), 偷窃 3 号房屋 (金额 = 9)，接着偷窃 5 号房屋 (金额 = 1)。
     偷窃到的最高金额 = 2 + 9 + 1 = 12 。

提示：
- 1 <= nums.length <= 100
- 0 <= nums[i] <= 400
*/

/*
解法一：二维 DP，把"第 i 间偷没偷"拆成两个状态【非最优】

为什么慢：直接对每间房枚举偷还是不偷，是 2^n 种组合再逐个检查相邻冲突；
更常见的贪心（每次都拿当前能拿的最大值）也不行，示例 2 里贪心最多拿到
9 + 1 = 10，而正确答案 12 来自 2 + 9 + 1。

换个角度：约束只发生在相邻两间之间，所以"前 i 间的最优值"只需要知道
第 i 间到底偷没偷。把这一位拆成状态，转移就与更早的房无关了。

关键点：
  · dp[i][1] 只能由 dp[i-1][0] 转移而来，这是"相邻不可同偷"的唯一落点
  · dp[i][0] 是两条来源取 max：第 i 间不偷时，第 i-1 间偷不偷都合法
  · 下标约定 dp[i] 描述"前 i 间"，金额取 nums[i-1]；两处下标错开一位
    就会把首尾的房算漏或算重
  · dp[0][*] = 0 是底座：一间房都没有时金额为 0
  · Rust 里用 [[i32; 2]] 而不是两个平行 Vec，减少一次下标换算

以示例 2（nums = [2,7,9,3,1]）为例，每步写 (不偷, 偷)：
  i=1： (0, 2)
  i=2： (max(0,2)=2, 0+7=7)
  i=3： (max(2,7)=7, 2+9=11)
  i=4： (max(7,11)=11, 7+3=10)
  i=5： (max(11,10)=11, 11+1=12)
  答案 max(11,12) = 12 ✔

复杂度分析：
  时间 O(n)：每间房做两次常数转移
  空间 O(n)：n+1 行的两列状态表
*/
pub struct Solution1;

impl Solution1 {
    pub fn rob(nums: Vec<i32>) -> i32 {
        let n = nums.len();
        // dp[i][0] / dp[i][1]：前 i 间里，第 i 间不偷 / 偷 时的最大金额
        let mut dp = vec![[0i32; 2]; n + 1];

        for i in 1..=n {
            dp[i][0] = dp[i - 1][0].max(dp[i - 1][1]);
            // 偷第 i 间，则第 i-1 间必须不偷
            dp[i][1] = dp[i - 1][0] + nums[i - 1];
        }

        dp[n][0].max(dp[n][1])
    }
}

/*
解法二：一维滚动，只留两个变量【最优解】

为什么慢：解法一其实只用到了相邻一行，却存了 n+1 行；而这题的最优值
只有"前一间的最优"和"前两间的最优"两个数在起作用，整张表是浪费。

换个角度：把"偷没偷"的一维状态消掉，直接记 dp[i] = 前 i 间的最大金额，
则要么不偷第 i 间（dp[i-1]），要么偷第 i 间（dp[i-2] + nums[i-1]）。
再往前滚一步，dp[i-1] 和 dp[i-2] 用两个变量就够。

关键点：
  · 转移式是 dp[i] = max(dp[i-1], dp[i-2] + x)，不是 max(dp[i-1], x)
    ——"偷了当前这间"必须放弃前一间，而不是只拿当前这间
  · cur 必须由旧的 prev2、prev1 算完再整体后移，先写 prev2 = prev1
    再算 cur 就会用错一代的值
  · 循环体只读 x，不按下标访问，空切片天然返回 0

以示例 2（nums = [2,7,9,3,1]）为例，记 (prev2, prev1)：
  初值 (0, 0)
  x=2：cur = max(0, 0+2) = 2 → (0, 2)
  x=7：cur = max(2, 0+7) = 7 → (2, 7)
  x=9：cur = max(7, 2+9) = 11 → (7, 11)
  x=3：cur = max(11, 7+3) = 10 → (11, 10)
  x=1：cur = max(10, 11+1) = 12 → (10, 12) ✔

复杂度分析：
  时间 O(n)：每间房一次 max
  空间 O(1)：只有 prev2 / prev1 / cur 三个整数
*/
pub struct Solution2;

impl Solution2 {
    pub fn rob(nums: Vec<i32>) -> i32 {
        // prev2 / prev1 分别是 dp[i-2] / dp[i-1]
        let (mut prev2, mut prev1) = (0, 0);

        for x in nums {
            // 当前这间要么跳过，要么接在"前两间的最优"后面
            let cur = prev1.max(prev2 + x);
            prev2 = prev1;
            prev1 = cur;
        }

        prev1
    }
}

fn check(nums: &[i32], want: i32) {
    assert_eq!(Solution1::rob(nums.to_vec()), want);
    assert_eq!(Solution2::rob(nums.to_vec()), want);
}

fn main() {
    // 示例 1：跳过 2 号房才能连拿 1 和 3
    check(&[1, 2, 3, 1], 4);

    // 示例 2：贪心拿 9 只能得 10，正确答案是 2+9+1
    check(&[2, 7, 9, 3, 1], 12);

    // 边界：只有一间房，必偷
    check(&[5], 5);

    // 边界：金额全为 0，答案 0（不是 -1）
    check(&[0], 0);
    check(&[0, 0, 0], 0);

    // 关键点用例：隔一间偷一次优于相邻两间，2+2 与 1+1 都是 4
    check(&[2, 1, 1, 2], 4);

    // 关键点用例：dp[i-2] 必须真的跳过相邻那间，答案是 4+7+3
    check(&[4, 1, 2, 7, 5, 3, 1], 14);

    // 边界：100 间房全为 400，只能隔一间偷，答案 50 * 400
    check(&vec![400; 100], 20000);

    println!("all tests passed");
}
