/*
============================================================================
134. 加油站（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/gas-station/
分类：贪心 · 前缀和 / 环形数组

在一条环路上有 n 个加油站，其中第 i 个加油站有汽油 gas[i] 升。

你有一辆油箱容量无限的的汽车，从第 i 个加油站开往第 i+1 个加油站需要
消耗汽油 cost[i] 升。你从其中的一个加油站出发，开始时油箱为空。

给定两个整数数组 gas 和 cost ，如果你可以按顺序绕环路行驶一周，则返回
出发时加油站的编号，否则返回 -1 。如果存在解，则 保证 它是 唯一 的。

示例 1：
输入: gas = [1,2,3,4,5], cost = [3,4,5,1,2]
输出: 3
解释:
从 3 号加油站(索引为 3 处)出发，可获得 4 升汽油。此时油箱有 = 0 + 4 = 4
开往 4 号加油站，此时油箱有 4 - 1 + 5 = 8 升汽油
开往 0 号加油站，此时油箱有 8 - 2 + 1 = 7 升汽油
开往 1 号加油站，此时油箱有 7 - 3 + 2 = 6 升汽油
开往 2 号加油站，此时油箱有 6 - 4 + 3 = 5 升汽油
开往 3 号加油站，你需要消耗 5 升汽油，正好足够你返回到 3 号加油站。
因此，3 可为起始索引。

示例 2：
输入: gas = [2,3,4], cost = [3,4,3]
输出: -1
解释:
你不能从 0 号或 1 号加油站出发，因为没有足够的汽油可以让你行驶到下一个
加油站。
我们从 2 号加油站出发，可以获得 4 升汽油。 此时油箱有 = 0 + 4 = 4
开往 0 号加油站，此时油箱有 4 - 3 + 2 = 3 升汽油
开往 1 号加油站，此时油箱有 3 - 3 + 3 = 3 升汽油
你无法返回 2 号加油站，因为返程需要消耗 4 升汽油，但是你的油箱只有 3 升
汽油。
因此，无论怎样，你都不可能绕环路行驶一周。

提示：
n == gas.length == cost.length
1 <= n <= 10^5
0 <= gas[i], cost[i] <= 10^4
输入保证答案唯一。
*/
#include <cassert>
#include <iostream>
#include <vector>
using namespace std;

/*
解法一：一次遍历（总油量判定 + 亏空处重启）【最优解】

为什么慢：最直白的做法是对每个起点模拟一圈，每个起点走 O(n) 步，
O(n^2)。瓶颈在于每个起点都从零重新走，之前路段的信息全被丢掉。

换个角度：把 gas[i] - cost[i] 记作第 i 段路的净收益 d[i]。跑完全程等价于
找 s，使从 s 出发的任意前缀和都不为负。如果从 s 走到 i 时油箱第一次变负，
那么 s..i 这一段的总收益为负 —— 从其中任何一点 j 出发只会更亏，因为
j 之前的那段收益是非负的。于是这一段里的所有起点可以一次性跳过。

关键点：
  · tank 只统计「从当前 start 起」的净收益，total 统计全程
  · tank < 0 时必须把 start 挪到 i + 1 且把 tank 清零，不能保留负数
  · 返回 -1 的判据是 total < 0，不是 tank < 0；tank 只反映最后一段
  · 题目保证有解时解唯一，所以「第一个可行起点」就是答案

为什么贪心是对的（跳过起点的反证）：
  · 设从 s 出发第一次在 i 处 tank < 0，记 D(a,b) 为 a..b 各段净收益之和。
    i 是第一个失败点 ⇒ 对任意 j ∈ [s, i] 都有 D(s, j-1) >= 0。
  · 从 j 出发到 i 的净收益 D(j, i) = D(s, i) - D(s, j-1)。
    已知 D(s, i) < 0、D(s, j-1) >= 0，故 D(j, i) < 0：
    j 连 i+1 都到不了，更不可能绕完一圈。
  · 因此 [s, i] 中没有任何可行起点，整体跳到 i+1 不会漏解。
  · total >= 0 时，最后一次重启后的 start 满足：此后到末尾每个前缀都
    非负；而跨圈部分由 total >= 0 与「start 处前缀和是全局最低」共同保证
    非负，所以它确实能绕完一圈。
    为什么它最低：每次 tank < 0 都说明当前前缀和 P[i+1] 低于本段基准
    P[start]；重启后基准换成更低的 P[i+1]，而段内每个 P 都不低于基准。
    基准一路只降不升，所以最后剩下的 P[start] 是全局最小。

以示例 1（gas = [1,2,3,4,5]，cost = [3,4,5,1,2]）为例：
  d = [-2,-2,-2,3,3]
  i=0：tank=-2 < 0 → start=1，tank=0
  i=1：tank=-2 < 0 → start=2，tank=0
  i=2：tank=-2 < 0 → start=3，tank=0
  i=3：tank=3；i=4：tank=6
  total = 0 >= 0 → 返回 3 ✔

复杂度分析：
  时间 O(n)：每个下标只进一次循环，重启后不回头
  空间 O(1)：只用了 total / tank / start
*/
class Solution1
{
public:
    // 返回可行的出发加油站下标；无解返回 -1
    int canCompleteCircuit(vector<int> &gas, vector<int> &cost)
    {
        int total = 0; // 整圈净收益，决定有没有解
        int tank = 0;  // 从 start 出发到当前的累计净收益
        int start = 0; // 当前候选起点

        for (int i = 0; i < static_cast<int>(gas.size()); ++i)
        {
            int delta = gas[i] - cost[i];
            total += delta;
            tank += delta;

            // 从 start 已经开不到 i+1，[start, i] 都不可能是起点
            if (tank < 0)
            {
                start = i + 1;
                tank = 0;
            }
        }
        // 总净收益为负时，任何起点绕一圈都会亏油
        return total >= 0 ? start : -1;
    }
};

/*
解法二：图表法（前缀和最低点之后出发）【最优解，与解法一并列】

为什么慢：同解法一，逐起点模拟是 O(n^2)；这里换一种把题目画出来的方式。

换个角度：把 d[i] = gas[i]-cost[i] 的前缀和 P 画成折线（P[0]=0，
P[k]=d[0]+...+d[k-1]）。从 s 出发，走过一段路后的油箱就是
「当前 P 的高度 - P[s] 的高度」。要让整段行程油箱都不为负，只要选 P 的
最低点作为基准 —— 从最低点出发，后面任何位置都不会比它更低。

关键点：
  · 起点是「前缀和最低的那个下标」，下标定义要和代码里的 start 对齐
  · 用严格小于更新：并列最低时任取一个都可行，取最先出现的即可
  · total < 0 时折线绕不回起点，直接 -1，最低点方法失效
  · total >= 0 时 P[n] >= P[0]，最低点不会落在 P[n]，start 必在 [0, n-1]

为什么贪心是对的（前缀和比较）：
  · 设 P[0]=0，P[k]=sum_{t<k} d[t]，total=P[n]。从 s 出发，经过
    s..t 后的累计净收益是 P[t+1]-P[s]（跨圈时 P 再加上 total）。
  · 若 P[s] 是 P[0..n-1] 的最小值，未跨圈时 P[t+1] >= P[s]，油箱非负；
    跨圈后 P[t+1] = total + P[j] >= P[j] >= P[s]（total >= 0），仍非负。
    于是从 s 出发可以绕完一圈。
  · 必要性：total < 0 时整圈净收益为负，任何起点都会在某一刻耗尽，返回 -1。
  · 与解法一等价：一次遍历里的每次重启，正是在把基准压到新的前缀和低点。

以示例 1（gas = [1,2,3,4,5]，cost = [3,4,5,1,2]）为例：
  d = [-2,-2,-2,3,3]
  P = [0,-2,-4,-6,-3]，total = 0
  最低点 P[3] = -6 → start = 3，返回 3 ✔

复杂度分析：
  时间 O(n)：一趟求前缀和与最低点
  空间 O(1)：只保留当前前缀和、最低值及其下标
*/
class Solution2
{
public:
    int canCompleteCircuit(vector<int> &gas, vector<int> &cost)
    {
        int n = static_cast<int>(gas.size());
        int total = 0;
        int prefix = 0;
        // 把「出发前」的 0 也算进候选，保证正收益时默认从 0 出发
        int minPrefix = 0;
        int start = 0;

        for (int i = 0; i < n; ++i)
        {
            int delta = gas[i] - cost[i];
            total += delta;
            prefix += delta;

            // 取严格更小的前缀和，并列时保留更靠前的起点
            if (prefix < minPrefix)
            {
                minPrefix = prefix;
                start = i + 1;
            }
        }
        // 折线终点低于起点，绕一圈净亏油
        if (total < 0) return -1;
        // total >= 0 保证最低点不在 P[n]，start 落在 [0, n-1]
        return start;
    }
};

namespace
{
// 同一组输入同时验证两种解法，避免只测到其中一种
void check(vector<int> gas, vector<int> cost, int want)
{
    Solution1 s1;
    assert(s1.canCompleteCircuit(gas, cost) == want);

    Solution2 s2;
    assert(s2.canCompleteCircuit(gas, cost) == want);
}
} // namespace

int main()
{
    // 示例 1：正确答案在中段，前三个起点都要被跳过
    check({1, 2, 3, 4, 5}, {3, 4, 5, 1, 2}, 3);

    // 示例 2：总油量不足，任何起点都不行
    check({2, 3, 4}, {3, 4, 3}, -1);

    // 边界：只有一个站且油够
    check({5}, {3}, 0);

    // 边界：只有一个站但油不够
    check({3}, {5}, -1);

    // 边界：总油量恰好为负，逐段看都像能走
    check({1, 1}, {2, 2}, -1);

    // 边界：总油量恰好为 0，只有唯一合法起点
    check({1, 2}, {2, 1}, 1);

    // 反直觉：起点在数组末尾，答案依赖跨圈后的累计油箱
    check({2, 0, 1}, {1, 2, 0}, 2);

    // 边界：全部为 0，任何起点都能绕完，按下标最小返回 0
    check({0, 0}, {0, 0}, 0);

    cout << "all tests passed" << endl;
    return 0;
}
