/*
============================================================================
542. 01 矩阵（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/01-matrix/
分类：广度优先搜索 · 多源最短路 / 动态规划

给定一个由 0 和 1 组成的矩阵 mat ，请输出一个大小相同的矩阵，其中每一个
格子是 mat 中对应位置元素到最近的 0 的距离。

两个相邻元素间的距离为 1 。

示例 1：
输入：mat = [[0,0,0],[0,1,0],[0,0,0]]
输出：[[0,0,0],[0,1,0],[0,0,0]]

示例 2：
输入：mat = [[0,0,0],[0,1,0],[1,1,1]]
输出：[[0,0,0],[0,1,0],[1,2,1]]

提示：
- m == mat.length
- n == mat[i].length
- 1 <= m, n <= 10^4
- 1 <= m * n <= 10^4
- mat[i][j] is either 0 or 1.
- mat 中至少有一个 0
*/
use std::collections::VecDeque;

/*
解法一：多源 BFS（所有 0 同时入队）【最优解】

为什么慢：对每个 1 单独做一次 BFS 找最近的 0，最坏 O((mn)^2)；反过来"对每个 0
跑一次 BFS 再取最小"也是同一个量级，因为同一片区域被反复扩散了很多遍。

换个角度：所有 0 都是源点，到自身的距离是 0，题目要的正是"每个格子到最近源点
的距离"。把全部 0 在第 0 层一起入队，一次 BFS 就能把所有格子的答案同时算出来。

为什么这里应当用 BFS 而不是 DFS：求"最近的 0"是无权图上的多源最短路。DFS 走到
某个 0 时无法知道别处是否存在更近的 0，只能把所有路径都枚举一遍取最小值；
而 BFS 按距离递增的顺序出队，第一次到达某格的距离就是最短距离，不需要比较。

关键点：
  · 直接把所有 0 入队并把 dist 置 0，队列一开始就有多个源点
  · 用 dist 是否已被赋值代替额外的 visited：BFS 里第一次写入的距离就是最短
  · 距离不必按层维护，出队时写 `dist[邻居] = dist[当前] + 1` 即可
  · 邻居只在 dist 仍为 -1 时才入队，否则会把已定型的格子改坏
  · Rust 用 `isize` 做坐标运算再判越界，避免 `usize` 相减回绕成巨值

手推一遍：
以示例 2（[[0,0,0],[0,1,0],[1,1,1]]）为例：
  第 0 层：全部 0，dist 为 0
  第 1 层：(1,1) 由四邻的 0 写入 1；(2,0) 由 (1,0) 写入 1；
          (2,2) 由 (1,2) 写入 1
  第 2 层：(2,1) 由 (2,0)/(2,2)/(1,1) 写入 2
  结果 [[0,0,0],[0,1,0],[1,2,1]] ✔

复杂度分析：
  时间 O(mn)：每个格子最多入队一次，出队时只看 4 个邻居
  空间 O(mn)：dist 矩阵 + 队列最坏同时存下全部格子
*/

// 单文件 rustc 编译时不存在平台的 Solution，这里显式声明为单元结构体
pub struct Solution1;

impl Solution1 {
    pub fn update_matrix(mat: Vec<Vec<i32>>) -> Vec<Vec<i32>> {
        let m = mat.len();
        let n = mat[0].len();

        // -1 表示"还没被任何 0 覆盖到"，同时充当 visited 标记
        let mut dist = vec![vec![-1i32; n]; m];
        let mut queue: VecDeque<(usize, usize)> = VecDeque::new();

        for i in 0..m {
            for j in 0..n {
                if mat[i][j] == 0 {
                    dist[i][j] = 0;
                    // 多源：所有 0 一起出发
                    queue.push_back((i, j));
                }
            }
        }

        let dirs: [(i32, i32); 4] = [(1, 0), (-1, 0), (0, 1), (0, -1)];
        while let Some((r, c)) = queue.pop_front() {
            for (dr, dc) in dirs.iter() {
                let nr = r as i32 + dr;
                let nc = c as i32 + dc;
                // 越界或被更早的层写过的格子，都不能再被更新
                if nr < 0 || nr >= m as i32 || nc < 0 || nc >= n as i32 {
                    continue;
                }
                let (nr, nc) = (nr as usize, nc as usize);
                if dist[nr][nc] != -1 {
                    continue;
                }

                dist[nr][nc] = dist[r][c] + 1;
                queue.push_back((nr, nc));
            }
        }

        dist
    }
}

/*
解法二：动态规划，两次扫描【最优解，与解法一并列】

为什么慢：BFS 要开队列，最坏把 O(mn) 个坐标同时压在队列里，每格出队还要做
四次越界判断。若只想要"每个格子到最近 0 的距离"这个数值，其实不必真的模拟
扩散过程——距离本身满足一个递推关系。

换个角度：离某个格子最近的 0，一定在它的四个斜象限之一。分两趟扫描：
  · 左上→右下：只看上方和左方，得到"从左上方向传过来的最短距离"
  · 右下→左上：只看下方和右方，补上右下方向的信息
一个格子的最终答案，就是这两趟里记下的较小值。

为什么两趟就够：任意一条从格子走到最近 0 的路径，都可以选成"先竖直再水平"
或"先水平再竖直"的单调路径。这条路径在两趟里各被传播过一段：先走的那段
由一趟记录，后走的那段由另一趟从拐点接上；两趟取最小，四个象限全覆盖。

关键点：
  · 第一趟之前，把所有 1 初始化成足够大的值（取 m + n，任何真实距离都比它小），
    否则"上方/左方还没有值"会被误当成 0
  · 第一趟的两个来源是 `dist[i-1][j]`、`dist[i][j-1]`，顺序必须是 i、j 都升序
  · 第二趟的两个来源是 `dist[i+1][j]`、`dist[i][j+1]`，顺序必须是 i、j 都降序
  · 0 格在每一趟都要显式写回 0，避免被 INF+1 覆盖
  · 与解法一的取舍：BFS 直观，语义就是"扩散"，但要队列；DP 不开队列、常数更小，
    且允许原地改写 mat 时额外空间可以压到 O(1)。本题返回值本身就是 m×n 的矩阵，
    两者对结果的空间量级一致，故并列最优

手推一遍：
以示例 2（[[0,0,0],[0,1,0],[1,1,1]]）为例：
  第一趟（左上→右下）：
    (1,1) 取 min(左上 0+1, 左 0+1) = 1
    (2,0) 取 min(上 1+1) = 2
    (2,1) 取 min(上 1+1, 左 2+1) = 2
    (2,2) 取 min(上 1+1, 左 2+1) = 2
  第二趟（右下→左上）：
    (2,1) 取 min(旧 2, 右 2+1) = 2；(2,0) 取 min(旧 2, 右 2+1) = 2；
    (1,1) 取 min(旧 1, 下 2+1) = 1
  结果 [[0,0,0],[0,1,0],[1,2,1]] ✔

复杂度分析：
  时间 O(mn)：两趟各扫一遍网格，每格常数次比较
  空间 O(mn)：dist 矩阵即返回值；若允许改写 mat，可省掉这份辅助空间
*/

pub struct Solution2;

impl Solution2 {
    pub fn update_matrix(mat: Vec<Vec<i32>>) -> Vec<Vec<i32>> {
        let m = mat.len();
        let n = mat[0].len();
        let inf = (m + n) as i32; // 任何真实距离都小于它，INF 只表示"尚未算出"

        let mut dist = vec![vec![inf; n]; m];

        // 第一趟：只允许从上方、左方传播
        for i in 0..m {
            for j in 0..n {
                if mat[i][j] == 0 {
                    dist[i][j] = 0;
                    continue;
                }
                if i > 0 {
                    dist[i][j] = dist[i][j].min(dist[i - 1][j] + 1);
                }
                if j > 0 {
                    dist[i][j] = dist[i][j].min(dist[i][j - 1] + 1);
                }
            }
        }

        // 第二趟：只允许从下方、右方传播，补上另一侧
        for i in (0..m).rev() {
            for j in (0..n).rev() {
                if mat[i][j] == 0 {
                    dist[i][j] = 0;
                    continue;
                }
                if i + 1 < m {
                    dist[i][j] = dist[i][j].min(dist[i + 1][j] + 1);
                }
                if j + 1 < n {
                    dist[i][j] = dist[i][j].min(dist[i][j + 1] + 1);
                }
            }
        }

        dist
    }
}

fn check(mat: Vec<Vec<i32>>, want: Vec<Vec<i32>>) {
    // 两个解法都只读 mat、另建 dist，不会互相污染
    assert_eq!(Solution1::update_matrix(mat.clone()), want, "bfs: {:?}", mat);
    assert_eq!(Solution2::update_matrix(mat.clone()), want, "dp: {:?}", mat);
}

fn main() {
    // 示例 1：0 把中间的 1 四面围住，距离 1
    check(
        vec![vec![0, 0, 0], vec![0, 1, 0], vec![0, 0, 0]],
        vec![vec![0, 0, 0], vec![0, 1, 0], vec![0, 0, 0]],
    );

    // 示例 2：右下角要绕一圈才够得着最近的 0，距离逐格递增
    check(
        vec![vec![0, 0, 0], vec![0, 1, 0], vec![1, 1, 1]],
        vec![vec![0, 0, 0], vec![0, 1, 0], vec![1, 2, 1]],
    );

    // 边界：只有一个 0
    check(vec![vec![0]], vec![vec![0]]);

    // 边界：0 在右侧，左侧的 1 必须往右走
    check(vec![vec![1, 0]], vec![vec![1, 0]]);

    // 边界：单列，只能沿竖直方向传播
    check(vec![vec![1], vec![0]], vec![vec![1], vec![0]]);

    // 边界：整行单点 0，距离就是列距
    check(
        vec![vec![0, 1, 1, 1], vec![1, 1, 1, 1]],
        vec![vec![0, 1, 2, 3], vec![1, 2, 3, 4]],
    );

    // 边界：只有左上角是 0，答案等于曼哈顿距离；两次扫描缺一趟都会错
    check(
        vec![
            vec![0, 1, 1, 1],
            vec![1, 1, 1, 1],
            vec![1, 1, 1, 1],
            vec![1, 1, 1, 1],
        ],
        vec![
            vec![0, 1, 2, 3],
            vec![1, 2, 3, 4],
            vec![2, 3, 4, 5],
            vec![3, 4, 5, 6],
        ],
    );

    // 边界：只有右下角是 0，专门检验第二趟扫描
    check(vec![vec![1, 1], vec![1, 0]], vec![vec![2, 1], vec![1, 0]]);

    println!("all tests passed");
}
