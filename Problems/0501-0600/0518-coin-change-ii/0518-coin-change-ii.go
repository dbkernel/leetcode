/*
============================================================================
518. 零钱兑换 II（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/coin-change-ii/
分类：动态规划 · 完全背包组合计数

给你一个整数数组 coins 表示不同面额的硬币，另给一个整数 amount 表示总金额。

请你计算并返回可以凑成总金额的硬币组合数。如果任何硬币组合都无法凑出总金额，返回 0 。

假设每一种面额的硬币有无限个。

题目数据 保证 最终 结果符合 32 位 带符号整数。

示例 1：
输入：amount = 5, coins = [1, 2, 5]
输出：4
解释：有四种方式可以凑成总金额：
5=5
5=2+2+1
5=2+1+1+1
5=1+1+1+1+1

示例 2：
输入：amount = 3, coins = [2]
输出：0
解释：只用面额 2 的硬币不能凑成总金额 3 。

示例 3：
输入：amount = 10, coins = [10]
输出：1

提示：
- 1 <= coins.length <= 300
- 1 <= coins[i] <= 5000
- coins 中的所有值 互不相同
- 0 <= amount <= 5000
*/
package main

import "fmt"

/*
解法一：二维 DP，按币种逐行递推【非最优】

为什么慢：按金额直接枚举"每种硬币各用几枚"是一次搜索，方案数一大分支就
爆炸；即便剪枝，同一组硬币也会因为"先定哪种面额"被枚举多遍。

换个角度：把"硬币种类"当成阶段。dp[i][j] 只回答一件事——允许使用前 i 种
硬币时，凑出金额 j 有多少种组合。引进第 i 种后，方案分成互斥的两类：不用
它（dp[i-1][j]），和至少用一枚（dp[i][j-coins[i-1]]），相加即可。

关键点：
  · "至少用一枚"这一项留在同一行 i，不回到 i-1 —— 留在 i 才表示第 i 种
    硬币还能继续用，写回 i-1 就把完全背包改成了 0-1 背包
  · dp[*][0] 全填 1：金额 0 由"一枚都不取"唯一凑出，是整张表的底座
  · 答案是 dp[n][amount] —— 阶段已经扫过全部币种，不能再对行求和，
    求和等于把不同币种数的方案重复记了多次

以示例 1（amount = 5, coins = [1,2,5]）为例，只看加入硬币 5 的那一行：
  dp[2][5] = 3，对应 1+1+1+1+1、2+1+1+1、2+2+1
  dp[3][5] = dp[2][5] + dp[3][0] = 3 + 1 = 4，多出来的是 5=5 ✔

复杂度分析：
  时间 O(n·amount)：n 个币种 × amount 个金额，每个状态 O(1)
  空间 O(n·amount)：每行都保留，但递推只用到上一行和本行左侧
*/
func change2D(amount int, coins []int) int {
	n := len(coins)
	// dp[i][j]：只用前 i 种硬币凑出金额 j 的组合数
	dp := make([][]int, n+1)
	for i := range dp {
		dp[i] = make([]int, amount+1)
		// 金额 0 是唯一的空组合，每一行都要作为底座
		dp[i][0] = 1
	}

	for i := 1; i <= n; i++ {
		for j := 1; j <= amount; j++ {
			dp[i][j] = dp[i-1][j]
			// 第 i 种至少用一枚，剩下的金额仍只能用前 i 种
			if j >= coins[i-1] {
				dp[i][j] += dp[i][j-coins[i-1]]
			}
		}
	}
	return dp[n][amount]
}

/*
解法二：一维滚动，物品在外、容量在内正序【最优解】

为什么慢：解法一只需要上一行，却把 n+1 行全留着，空间随币种数线性增长；
而 amount 最大 5000、币种最多 300，二维表要 150 万个格子。

换个角度：把 dp 压成一行，边扫币种边在原地更新。外层固定一种硬币、内层
金额正序，等价于"每加入一种硬币，就把它能拼接的位置往后推一次"，正好复用
了刚刚更新过的左侧值。

关键点：
  · 外层必须是硬币、内层必须是金额，且金额正序 —— 三者一起才保证
    "组合"而不是"排列"：每种硬币只在自己那一轮被无限次使用，
    硬币之间没有先后顺序可选
  · 一旦把两层调换（金额在外、硬币在内），dp[j] 会累加"最后一步用哪枚
    硬币"的所有选择，同一组硬币的不同排列被算成不同方案，
    那正是 377 组合总和 Ⅳ 的答案。同一输入 amount=5、coins=[1,2,5]，
    本题得 4，调换后得 9
  · 内层从 c 起步而不是从 0 起步：j < c 时用不了这枚硬币，dp[j] 保持原值，
    这个"跳过"恰好就是二维写法里的 dp[i-1][j]
  · dp[0] = 1 在循环外只设一次，循环内不许重置

以示例 1（amount = 5, coins = [1,2,5]）为例：
  初值 dp = [1,0,0,0,0,0]
  硬币 1：dp = [1,1,1,1,1,1]
  硬币 2：dp = [1,1,2,2,3,3]（dp[j] += dp[j-2]）
  硬币 5：dp[5] += dp[0] → 4 ✔

复杂度分析：
  时间 O(n·amount)：每枚硬币把金额表扫一遍
  空间 O(amount)：只留一行，amount 为 0 时退化为 1 个格子
*/
func change(amount int, coins []int) int {
	dp := make([]int, amount+1)
	dp[0] = 1

	for _, c := range coins {
		// 正序：允许同一枚硬币在一轮里被重复使用
		for j := c; j <= amount; j++ {
			dp[j] += dp[j-c]
		}
	}
	return dp[amount]
}

func check(amount int, coins []int, want int) {
	if got := change2D(amount, coins); got != want {
		panic(fmt.Sprintf("change2D(%d, %v) = %d, want %d", amount, coins, got, want))
	}
	if got := change(amount, coins); got != want {
		panic(fmt.Sprintf("change(%d, %v) = %d, want %d", amount, coins, got, want))
	}
}

func main() {
	// 示例 1：1、2、5 三种面额，组合与排列的分歧从这里开始显现
	check(5, []int{1, 2, 5}, 4)

	// 示例 2：无法凑出的金额必须是 0，不是 -1
	check(3, []int{2}, 0)

	// 示例 3：只有一枚等于目标金额的硬币
	check(10, []int{10}, 1)

	// 边界：金额 0 —— 空组合算一种，任何面额下答案都是 1
	check(0, []int{1, 2}, 1)

	// 边界：需要多枚不同面额拼出目标，且只有一种拼法
	check(5, []int{2, 3}, 1)

	// 关键点用例：组合数为 2（1+1+1、1+2），若循环顺序写反会得到 3
	check(3, []int{1, 2}, 2)

	// 关键点用例：面额 1 与 2 拼 4，组合 3 种（1111、112、22）
	check(4, []int{1, 2}, 3)

	// 边界：最大金额、单一面额，答案必然为 1
	check(5000, []int{1}, 1)

	// 边界：所有面额都大于目标金额
	check(1, []int{2, 5}, 0)

	fmt.Println("all tests passed")
}
