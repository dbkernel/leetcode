/*
============================================================================
LeetCode 1047. 删除字符串中的所有相邻重复项（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/remove-all-adjacent-duplicates-in-string/
分类：栈 · 相邻消除
============================================================================

给出由小写字母组成的字符串 s，重复项删除操作 会选择两个相邻且相同的字母，
并删除它们。

在 s 上反复执行重复项删除操作，直到无法继续删除。

在完成所有重复项删除操作后返回最终的字符串。答案保证唯一。

示例 1：
输入："abbaca"
输出："ca"
解释：
例如，在 "abbaca" 中，我们可以删除 "bb" 由于两字母相邻且相同，这是此时
唯一可以执行删除操作的重复项。之后我们得到字符串 "aaca"，其中又只有 "aa"
可以执行重复项删除操作，所以最后的字符串为 "ca"。

示例 2：
输入：s = "azxxzy"
输出："ay"

提示：
1 <= s.length <= 10^5
s 仅由小写英文字母组成。
*/
package main

import "fmt"

/*
解法：栈（当前字符与栈顶相同就弹出栈顶）【最优解】

官方题解只给出这一种方法，它同时也就是本题的最优解：每个字符进出栈各一次，
时间 O(n) 已是下界，空间 O(n) 用来存结果串。

为什么慢：反复「从头扫一遍，发现一对就删掉，再从删处往回退」看着直观，
但每次删除都会让后面的字符整体前移，最坏情况 O(n^2)；而且删完之后
新的相邻关系会跨过删除位置，容易漏检。

换个角度：删除一对相邻相同字符后，它左边和右边的字符会变成新的相邻对 ——
这正是「后进先出」：先消掉靠后的，才轮到跨过它的那一对。用栈表达最自然：
读入一个字符，若它与栈顶相同，两者一起消掉（弹栈）；否则压栈。

关键点：
  · 只和栈顶比较，不要和「已处理结果的其他位置」比较
  · 相等时只弹栈，不压入当前字符 —— 两个一起消失
  · 栈空时直接压入，不要读栈顶（会越界）
  · 直接把结果切片当栈用，弹出就是切片截断，省掉一次反向拷贝

Go 的一处写法说明：
  · 官方解法用 []byte 当栈，最后 string(stack) 转回来；本题只有 ASCII 字符，
    按字节处理是安全的，也比 []rune 更省

以示例 1（s = "abbaca"）为例：
  'a' 压栈 → 栈 "a"
  'b' 与栈顶 'a' 不同 → 栈 "ab"
  'b' 与栈顶 'b' 相同 → 弹出 → 栈 "a"
  'a' 与栈顶 'a' 相同 → 弹出 → 栈 ""
  'c' 压栈 → 栈 "c"
  'a' 压栈 → 栈 "ca"
  结果 "ca"

复杂度分析：
  时间 O(n)：每个字符最多压栈、弹栈各一次
  空间 O(n)：答案串本身，最坏情况（无相邻重复）长度等于 n
*/

// 反复消除相邻重复项，返回最终字符串
func removeDuplicates(s string) string {
	stack := make([]byte, 0, len(s))

	for i := 0; i < len(s); i++ {
		ch := s[i]
		// 栈空时没有栈顶可比，直接压入
		if len(stack) > 0 && stack[len(stack)-1] == ch {
			// 两个一起消失：只弹栈，不压入当前字符
			stack = stack[:len(stack)-1]
		} else {
			stack = append(stack, ch)
		}
	}

	return string(stack)
}

// ---- 以下为自测代码，不属于题解主体 ----

// 一个用例 = 输入 + 期望输出
func check(s, want string) {
	if got := removeDuplicates(s); got != want {
		panic(fmt.Sprintf("removeDuplicates(%q) = %q, want %q", s, got, want))
	}
}

func main() {
	// 示例 1：删除 bb 之后 aa 才成为新的相邻对，验证「连锁消除」
	check("abbaca", "ca")

	// 示例 2：先删 xx，再检查剩下的相邻对
	check("azxxzy", "ay")

	// 边界：没有相邻重复，结果应与输入相同
	check("abcd", "abcd")

	// 边界：完全两两抵消，结果为空串
	check("aabb", "")

	// 边界：单字符，栈空判断分支必须生效
	check("a", "a")

	fmt.Println("all tests passed")
}
