/*
============================================================================
LeetCode 1108. IP 地址无效化（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/defanging-an-ip-address/
分类：字符串 · 一次遍历替换
============================================================================

给你一个有效的 IPv4 地址 address，返回这个 IP 地址的无效化版本。

所谓无效化 IP 地址，其实就是用 "[.]" 代替了每个 "."。

示例 1：
输入：address = "1.1.1.1"
输出："1[.]1[.]1[.]1"

示例 2：
输入：address = "255.100.50.0"
输出："255[.]100[.]50[.]0"

提示：
给出的 address 是一个有效的 IPv4 地址
*/
package main

import (
	"fmt"
	"strings"
)

/*
解法：直接遍历（逐字符决定输出片段）【最优解】

官方题解只给出这一种方法，它同时也就是本题的最优解：每个字符都得看一遍，
O(n) 已是下界。

为什么慢：若在原串上用插入的方式就地替换，每插入一个字符都要把后面所有
字符整体后移，n 次插入最坏退化成 O(n^2)，还要反复扩容。

换个角度：无效化的结果只由「当前字符是不是 '.'」决定 —— 是就输出 "[.]"，
不是就原样输出。于是不必修改原串，一趟扫描把片段拼进新串即可。

关键点：
  · 语言自带的整体替换（strings.ReplaceAll）与手写遍历等价，都只扫一遍
  · 手写时判 '.' 用字节比较，不要退化成查找子串

Go 的两处写法说明：
  · strings.ReplaceAll 是最短的写法，与官方 Go 版一致，内部同样一次扫描
  · 用 strings.Builder 手写时记得 Grow 预分配，避免反复扩容复制

以示例 1（address = "1.1.1.1"）为例：
  读到 '1' → 追加 "1"
  读到 '.' → 追加 "[.]"
  后续相同，最终得到 "1[.]1[.]1[.]1"

复杂度分析：
  时间 O(n)：每个字符访问一次，追加是摊还 O(1)
  空间 O(1)：除返回值外不需要额外存储
             （返回值占 O(n)，按官方口径不计入）
*/

// 返回把每个 '.' 换成 "[.]" 之后的字符串，不修改入参
func defangIPaddr(address string) string {
	// ReplaceAll 一趟扫描直接构造新串，语义与手写遍历完全一致
	return strings.ReplaceAll(address, ".", "[.]")
}

// ---- 以下为自测代码，不属于题解主体 ----

// 一个用例 = 输入 + 期望输出；字符串直接用 == 比较
func check(address, want string) {
	if got := defangIPaddr(address); got != want {
		panic(fmt.Sprintf("address %q: got %q, want %q", address, got, want))
	}
}

func main() {
	// 示例 1：最典型的四段地址
	check("1.1.1.1", "1[.]1[.]1[.]1")

	// 示例 2：每段都是三位数，验证长片段的拼接
	check("255.100.50.0", "255[.]100[.]50[.]0")

	// 边界：全 0 地址，输入里没有任何多余字符可被误替换
	check("0.0.0.0", "0[.]0[.]0[.]0")

	// 边界：私有网段常见地址，验证不会漏掉任何一个点
	check("192.168.1.1", "192[.]168[.]1[.]1")

	fmt.Println("all tests passed")
}
