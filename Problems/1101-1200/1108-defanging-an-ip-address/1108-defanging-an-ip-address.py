'''
============================================================================
LeetCode 1108. IP 地址无效化（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/defanging-an-ip-address/
分类：字符串 · 一次遍历替换
============================================================================

给你一个有效的 IPv4 地址 address，返回这个 IP 地址的无效化版本。

所谓无效化 IP 地址，其实就是用 "[.]" 代替了每个 "."。

示例 1：
输入：address = "1.1.1.1"
输出："1[.]1[.]1[.]1"

示例 2：
输入：address = "255.100.50.0"
输出："255[.]100[.]50[.]0"

提示：
给出的 address 是一个有效的 IPv4 地址
'''

# ============================================================================
# 解法：直接遍历（逐字符决定输出片段）【最优解】
#
# 官方题解只给出这一种方法，它同时也就是本题的最优解：每个字符都得看一遍，
# O(n) 已是下界。
#
# 为什么慢：若在原串上用插入的方式就地替换，每插入一个字符都要把后面所有
# 字符整体后移，n 次插入最坏退化成 O(n^2)；Python 的 str 又是不可变对象，
# 任何「改一个字符」的写法其实都会复制整个串。
#
# 换个角度：无效化的结果只由「当前字符是不是 '.'」决定 —— 是就输出 "[.]"，
# 不是就原样输出。于是不必修改原串，一趟扫描把片段拼进新串即可。
#
# 关键点：
#   · str.replace 与手写遍历等价，都只扫一遍；官方 Python 版直接用了 replace
#   · 手写时不要用 += 在循环里拼接长串，那是 O(n^2)
#
# 以示例 1（address = "1.1.1.1"）为例：
#   读到 '1' → 追加 "1"
#   读到 '.' → 追加 "[.]"
#   后续相同，最终得到 "1[.]1[.]1[.]1"
#
# 复杂度分析：
#   时间 O(n)：每个字符访问一次，追加是摊还 O(1)
#   空间 O(1)：除返回值外不需要额外存储
#              （返回值占 O(n)，按官方口径不计入）
# ============================================================================


class Solution:
    # 返回把每个 '.' 换成 "[.]" 之后的字符串，不修改入参
    def defangIPaddr(self, address: str) -> str:
        # str 不可变，replace 天然构造新串，不会改到调用方的变量
        return address.replace(".", "[.]")


# ---- 以下为自测代码，不属于题解主体 ----


def check(address: str, want: str) -> None:
    """一个用例 = 输入 + 期望输出；字符串直接用 == 比较"""
    got = Solution().defangIPaddr(address)
    assert got == want, f"address {address!r}: got {got!r}, want {want!r}"


def main() -> None:
    # 示例 1：最典型的四段地址
    check("1.1.1.1", "1[.]1[.]1[.]1")

    # 示例 2：每段都是三位数，验证长片段的拼接
    check("255.100.50.0", "255[.]100[.]50[.]0")

    # 边界：全 0 地址，输入里没有任何多余字符可被误替换
    check("0.0.0.0", "0[.]0[.]0[.]0")

    # 边界：私有网段常见地址，验证不会漏掉任何一个点
    check("192.168.1.1", "192[.]168[.]1[.]1")

    print("all tests passed")


if __name__ == "__main__":
    main()
