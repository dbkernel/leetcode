'''
============================================================================
LeetCode 58. 最后一个单词的长度（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/length-of-last-word/
分类：字符串 · 反向遍历
============================================================================

给你一个字符串 s，由若干单词组成，单词前后用一些空格字符隔开。返回字符串中
最后一个 单词的长度。

单词 是指仅由字母组成、不包含任何空格字符的最大子字符串。

示例 1：
输入：s = "Hello World"
输出：5
解释：最后一个单词是"World"，长度为 5。

示例 2：
输入：s = "   fly me   to   the moon  "
输出：4
解释：最后一个单词是"moon"，长度为 4。

示例 3：
输入：s = "luffy is still joyboy"
输出：6
解释：最后一个单词是长度为 6 的"joyboy"。

提示：
1 <= s.length <= 10^4
s 仅有英文字母和空格 ' ' 组成
s 中至少存在一个单词
'''

# ============================================================================
# 解法：反向遍历（先跳尾空格，再数连续字母）【最优解】
#
# 官方题解只给出这一种方法，它同时也就是本题的最优解：只关心末尾那一段，
# 从后往前扫到最后一个单词开头即可停手，不必遍历前面的内容。
#
# 为什么慢：从头正向遍历得记住「上一个单词有多长」，而且必须先跳过全部内容
# 才知道哪个是最后一个；字符串末尾还有一堆空格时，正向扫描白读了大半。
#
# 换个角度：最后一个单词的位置由尾部决定。从末尾往前走：
# 第一步跳过尾部空格，找到最后一个字母；第二步从这个字母继续往前数，直到
# 遇到空格或走到字符串起点，数出来的个数就是答案。
#
# 关键点：
#   · 第一步的跳空格不必判越界 —— 题目保证至少有一个单词，尾部空格之后
#     必然还剩下一个字母
#   · 第二步必须写 index >= 0 这个条件 —— 整个串只有一个单词时（如 "a"），
#     指针会一路走到 -1，少了这个判断就会越界（Python 会静默取到末字符）
#   · 起始下标是 len(s) - 1，不是 len(s)
#
# Python 的一处写法说明：
#   · 负下标在 Python 里合法，写成 s[-1] 形式更直观，但仍要显式维护
#     index >= 0，否则越界后不会报错、而是绕回尾部，得到错误答案
#
# 以示例 2（s = "   fly me   to   the moon  "）为例：
#   从末尾跳过两个空格，指针落在 'n' 上
#   往前数 n、o、o、m，再往前是空格，停止 → 长度 4
#
# 复杂度分析：
#   时间 O(n)：最坏情况下整个串没有多余空格，也只扫一遍
#   空间 O(1)：只用两个整数
# ============================================================================


class Solution:
    def lengthOfLastWord(self, s: str) -> int:
        index = len(s) - 1

        # 跳过尾部空格：题目保证至少有一个单词，所以不会跳过整个串
        while s[index] == " ":
            index -= 1

        word_length = 0
        # index >= 0 不可省：单单词字符串会一路退到 -1
        while index >= 0 and s[index] != " ":
            word_length += 1
            index -= 1

        return word_length


# ---- 以下为自测代码，不属于题解主体 ----


def check(s: str, want: int) -> None:
    """一个用例 = 输入 + 期望输出"""
    got = Solution().lengthOfLastWord(s)
    assert got == want, f"lengthOfLastWord({s!r}) = {got}, want {want}"


def main() -> None:
    # 示例 1：无多余空格的最短输入
    check("Hello World", 5)

    # 示例 2：尾部有两个空格，验证先跳空格再数
    check("   fly me   to   the moon  ", 4)

    # 示例 3：多单词，验证数到空格就停
    check("luffy is still joyboy", 6)

    # 边界：只有一个单词，指针会一路退到 -1，专防越界
    check("a", 1)

    # 边界：单单词 + 前后各若干空格
    check("   day   ", 3)

    print("all tests passed")


if __name__ == "__main__":
    main()
