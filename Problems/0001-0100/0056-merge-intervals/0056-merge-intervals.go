/*
============================================================================
56. 合并区间（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/merge-intervals/
分类：排序 · 区间合并（贪心）

以数组 intervals 表示若干个区间的集合，其中单个区间为 intervals[i] = [start_i, end_i] 。
请你合并所有重叠的区间，并返回 一个不重叠的区间数组，该数组需恰好覆盖输入中的所有区间 。

示例 1：
输入：intervals = [[1,3],[2,6],[8,10],[15,18]]
输出：[[1,6],[8,10],[15,18]]
解释：区间 [1,3] 和 [2,6] 重叠, 将它们合并为 [1,6].

示例 2：
输入：intervals = [[1,4],[4,5]]
输出：[[1,5]]
解释：区间 [1,4] 和 [4,5] 可被视为重叠区间。

示例 3：
输入：intervals = [[4,7],[1,4]]
输出：[[1,7]]
解释：区间 [1,4] 和 [4,7] 可被视为重叠区间。

提示：
1 <= intervals.length <= 10^4
intervals[i].length == 2
0 <= start_i <= end_i <= 10^4
*/
package main

import (
	"fmt"
	"reflect"
	"sort"
)

/*
解法一：按左端点排序后贪心合并【最优解】

官方题解只给出这一种方法，也就是本题的最优解：时间 O(n log n)、空间 O(log n)。

为什么慢：如果不排序，一个区间可能和「前面很远」的区间重叠，你必须两两比较，
退化成 O(n^2)；而且合并完的大区间还可能再和别的区间重叠，得反复扫描。

换个角度：只按左端点升序排一次，就能得到一个关键性质——
「所有能合并的区间，在排好序的列表里一定是连续的」。
于是问题变成一次线性扫描：维护一个已合并结果的末尾区间，逐个吞并后续区间即可。
官方的正确性证明用反证法：若排序后 a[i]、a[k] 可合并而中间的 a[j] 没被合并进去，
就会和 a[j] 与 a[k] 的端点关系矛盾。

关键点：
  · 排序键必须用左端点（不能用右端点），用 sort.Slice 自定义比较
  · 判定「不重叠」的条件是 last[1] < L（当前区间左端点严格大于末尾右端点）。
    注意 [1,4] 与 [4,5] 端点相接也算重叠，所以用严格小于，不能用 <=
  · 合并时右端点取 max(last[1], R)——当前区间可能完全被已合并区间包住
    （例如 [[1,10],[2,3]]），无脑赋值 last[1] = R 会把区间改小
  · ans 里存的是切片的「头」引用，修改 last[1] 会直接改到底层数组，无需写回
  · 结果天然按左端点有序，且互不重叠

以 [[1,3],[2,6],[8,10],[15,18]] 为例：
  排序后不变
  ans = [[1,3]]
  [2,6]：2 <= 3 → 合并 → ans = [[1,6]]
  [8,10]：8 > 6 → 不重叠，追加 → [[1,6],[8,10]]
  [15,18]：15 > 10 → 追加 → [[1,6],[8,10],[15,18]]
  返回该结果

复杂度分析：
  时间 O(n log n)：排序 O(n log n) + 一次线性扫描 O(n)
  空间 O(log n)：排序所需的递归栈（不计答案数组）
*/

// 解法一：按左端点排序后贪心合并（最优解）
func merge(intervals [][]int) [][]int {
	ans := [][]int{}
	if len(intervals) == 0 {
		return ans
	}

	// 按左端点升序
	sort.Slice(intervals, func(i, j int) bool {
		return intervals[i][0] < intervals[j][0]
	})

	ans = append(ans, intervals[0])
	for i := 1; i < len(intervals); i++ {
		last := ans[len(ans)-1]
		L, R := intervals[i][0], intervals[i][1]
		// 与末尾区间不重叠（端点相接仍算重叠，故用严格小于）
		if last[1] < L {
			ans = append(ans, intervals[i])
		} else {
			// 当前区间可能被末尾区间完全包住，所以取两者较大值
			if R > last[1] {
				last[1] = R
			}
		}
	}
	return ans
}

func check(intervals [][]int, want [][]int) {
	// 传深拷贝，避免排序和合并改动测试输入
	input := make([][]int, len(intervals))
	for i, v := range intervals {
		input[i] = append([]int(nil), v...)
	}
	got := merge(input)
	if !reflect.DeepEqual(got, want) {
		panic(fmt.Sprintf("merge(%v) = %v, want %v", intervals, got, want))
	}
}

func main() {
	// 示例 1
	check([][]int{{1, 3}, {2, 6}, {8, 10}, {15, 18}}, [][]int{{1, 6}, {8, 10}, {15, 18}})

	// 示例 2：端点相接也要合并
	check([][]int{{1, 4}, {4, 5}}, [][]int{{1, 5}})

	// 示例 3：输入无序
	check([][]int{{4, 7}, {1, 4}}, [][]int{{1, 7}})

	// 边界：只有一个区间
	check([][]int{{1, 1}}, [][]int{{1, 1}})

	// 边界：完全互不相交
	check([][]int{{1, 2}, {5, 6}, {9, 10}}, [][]int{{1, 2}, {5, 6}, {9, 10}})

	// 边界：被完全包含的区间（右端点不能取小值）
	check([][]int{{1, 10}, {2, 3}}, [][]int{{1, 10}})
	check([][]int{{1, 10}, {2, 3}, {4, 5}}, [][]int{{1, 10}})

	// 边界：链式重叠，全部合成一个
	check([][]int{{1, 4}, {2, 3}, {3, 6}, {5, 7}}, [][]int{{1, 7}})

	// 边界：相同区间重复出现
	check([][]int{{1, 2}, {1, 2}, {1, 2}}, [][]int{{1, 2}})

	// 边界：最大取值范围
	check([][]int{{0, 0}, {0, 10000}}, [][]int{{0, 10000}})

	fmt.Println("all tests passed")
}
