/*
============================================================================
62. 不同路径（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/unique-paths/
分类：动态规划 · 网格路径计数 / 组合数学

一个机器人位于一个 m x n 网格的左上角 （起始点在下图中标记为 “Start” ）。

机器人每次只能向下或者向右移动一步。机器人试图达到网格的右下角（在下图中标记为 “Finish” ）。

问总共有多少条不同的路径？

示例 1：
输入：m = 3, n = 7
输出：28

示例 2：
输入：m = 3, n = 2
输出：3
解释：
从左上角开始，总共有 3 条路径可以到达右下角。
1. 向右 -> 向下 -> 向下
2. 向下 -> 向下 -> 向右
3. 向下 -> 向右 -> 向下

示例 3：
输入：m = 7, n = 3
输出：28

示例 4：
输入：m = 3, n = 3
输出：6

提示：
- 1 <= m, n <= 100
- 题目数据保证答案小于等于 2 * 10^9
*/
package main

import "fmt"

/*
解法一：动态规划 + 一维滚动【非最优】

为什么慢：从 (0,0) 一路 DFS 到终点，每条路径都要走到头才知道能不能成，
遍历次数与答案同阶——最大可达 10^58 条，完全不可行；而且同一个格子的
后半段路径会被不同前缀反复重算。

换个角度：到达 (i,j) 的最后一步只可能来自上方 (i-1,j) 或左方 (i,j-1)，
所以"到 (i,j) 的路径数"等于这两处之和。它与"具体是怎么走到这里的"无关，
只与行列下标有关，逐格递推即可。

关键点：
  · dp[j] 更新前是上一行同列的值，更新后是本行同列的值，所以能原地滚动
  · dp[j] += dp[j-1] 里的 dp[j-1] 必须已经是本行更新过的值，因此 j 从小到大
  · 第一行只有"一直向右"一种走法，dp 全部初始化成 1 正好对上
  · 答案就是 dp[n-1]，不需要再取 max 或求和

手推一遍：以示例 4（m = 3, n = 3）为例：
  初始 dp = [1,1,1]（第一行）
  第二行：dp[1] = 1+1 = 2，dp[2] = 1+2 = 3 → [1,2,3]
  第三行：dp[1] = 2+1 = 3，dp[2] = 3+3 = 6 → [1,3,6]
  → 答案 6 ✔

复杂度分析：
  时间 O(m*n)：每个格子算一次
  空间 O(n)：只保留一行，n 是列数；把较短的一边放在列上即 O(min(m,n))
*/
func uniquePathsDp(m int, n int) int {
	// dp[j]：到达当前行第 j 列的不同路径数，初值对应第一行全 1
	dp := make([]int, n)
	for j := range dp {
		dp[j] = 1
	}

	for i := 1; i < m; i++ {
		// 原地更新：dp[j] 的旧值是上方，dp[j-1] 的新值是左方
		for j := 1; j < n; j++ {
			dp[j] += dp[j-1]
		}
	}
	return dp[n-1]
}

/*
解法二：组合数学 C(m+n-2, m-1)【最优解】

为什么慢：解法一把每个格子都递推了一遍，可这道题的转移系数全是 1，
网格又是满的，逐格累加只是在机械地重复同一个加法——没必要付出 O(m*n)。

换个角度：任何一条路径都恰好包含 m-1 次向下和 n-1 次向右，总步数固定为
m+n-2。于是"一条路径"等价于"在 m+n-2 个位置里挑出 m-1 个放向下"，
答案是组合数 C(m+n-2, m-1)。

关键点：
  · 取 k = min(m-1, n-1) 做乘法：C(N,k) = C(N,N-k)，乘法次数降到 min(m,n)
  · 每乘一项立刻除一项，res 始终等于某个组合数，除法必定整除
  · 反过来"先连乘 k 项再除 k!"必爆：C(198,99) 约 9*10^58，64 位都装不下
  · 中间量 res * (N-k+i) 上界约 2*10^9 * 199 ≈ 4*10^11，用 int64 算
  · 题目保证答案 ≤ 2*10^9 < 2^31-1，所以返回值用 int 装得下
  · m 或 n 为 1 时 k = 0，循环不执行，直接返回 1

手推一遍：以示例 1（m = 3, n = 7）为例：
  N = 8，k = min(2, 6) = 2
  i = 1：res = 1 * 7 / 1 = 7
  i = 2：res = 7 * 8 / 2 = 28 → 答案 28 ✔

复杂度分析：
  时间 O(min(m,n))：只有 k 次乘除，且全程 O(1) 内存访问
  空间 O(1)：只用了几个标量
*/
func uniquePaths(m int, n int) int {
	// 总步数固定，挑较小的那一侧做乘法，循环次数最少
	total := m + n - 2
	k := m - 1
	if n-1 < k {
		k = n - 1
	}

	res := int64(1)
	for i := 1; i <= k; i++ {
		// 乘完立刻除：res 每一步都是组合数，除法整除且中间量不会溢出
		res = res * int64(total-k+i) / int64(i)
	}
	return int(res)
}

// 暴力参考解：把所有路径真正走一遍，只适合小网格
func brutePaths(r int, c int, m int, n int) int {
	if r == m-1 && c == n-1 {
		return 1
	}

	cnt := 0
	if r+1 < m {
		cnt += brutePaths(r+1, c, m, n)
	}
	if c+1 < n {
		cnt += brutePaths(r, c+1, m, n)
	}
	return cnt
}

// 两种解法必须给出同一个答案
func check(m int, n int, want int) {
	if got := uniquePathsDp(m, n); got != want {
		panic(fmt.Sprintf("dp(%d,%d) = %d, want %d", m, n, got, want))
	}
	if got := uniquePaths(m, n); got != want {
		panic(fmt.Sprintf("comb(%d,%d) = %d, want %d", m, n, got, want))
	}
}

// 小网格额外走一遍暴力枚举；大网格的路径数与答案同阶，只做解法间比对
func checkBrute(m int, n int) {
	check(m, n, brutePaths(0, 0, m, n))
}

func main() {
	// 示例 1
	check(3, 7, 28)

	// 示例 2：3 条路径，手写枚举可对
	check(3, 2, 3)

	// 示例 3：与示例 1 互为转置，答案必须相同
	check(7, 3, 28)

	// 示例 4
	check(3, 3, 6)

	// 边界：只有一格，原地不动就是一种走法
	check(1, 1, 1)

	// 边界：单行 / 单列，只有一条路
	check(1, 100, 1)
	check(100, 1, 1)

	// 边界：2x2
	check(2, 2, 2)

	// 边界：组合数递增，检验"乘一项除一项"是否整除
	check(11, 11, 184756)

	// 边界：答案接近 2*10^9 上限，检验 int 装得下、中间量不溢出
	check(17, 17, 601080390)

	// 小网格与暴力枚举对拍
	checkBrute(2, 3)
	checkBrute(4, 5)

	// 随机对拍：1..7 的网格，逐组与暴力计数比对
	seed := uint32(20260809)
	next := func(mod uint32) int {
		seed = seed*1103515245 + 12345
		return int((seed >> 16) % mod)
	}
	for t := 0; t < 60; t++ {
		m := 1 + next(7)
		n := 1 + next(7)
		checkBrute(m, n)
	}

	fmt.Println("all tests passed")
}
