/*
============================================================================
283. 移动零（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/move-zeroes/
分类：双指针 · 原地数组重排

给定一个数组 nums，编写一个函数将所有 0 移动到数组的末尾，同时保持非零元素的
相对顺序。

请注意 ，必须在不复制数组的情况下原地对数组进行操作。

示例 1：
输入: nums = [0,1,0,3,12]
输出: [1,3,12,0,0]

示例 2：
输入: nums = [0]
输出: [0]

提示：
- 1 <= nums.length <= 10^4
- -2^31 <= nums[i] <= 2^31 - 1

进阶：你能尽量减少完成的操作次数吗？
*/
#include <cassert>
#include <climits>
#include <iostream>
#include <vector>
using namespace std;

/*
解法一：双指针（一次遍历，非零元素与零原地交换）【最优解】

为什么慢：最直白的写法是"每遇到一个 0，就把后面整段往前挪一格，再在末尾
补 0"。挪动是逐元素拷贝，全 0 数组里第 i 个 0 要搬 n-i 个元素，总操作数
是 O(n^2)。另一种"先把非零元素收进新数组再拷回"时间 O(n)，但额外开了
O(n) 空间，直接违反题面的"不复制数组"。

换个角度：不要去搬 0，而是去收集非零元素。用 i 指向"下一个非零元素应该
落在哪里"，j 只负责从头到尾扫描：j 碰到非零就和 i 交换，i 前进一格。
0 被交换动作自然甩到了后面，不需要单独处理。

关键点：
  · i 只在写入非零元素后前进，所以恒有 i <= j，交换的两个位置都在已扫描
    过的区间内，不会覆盖还没读到的元素
  · 用 swap 而不是 nums[i] = nums[j]：赋值会把 j 处的非零元素留下两份，
    而 swap 把 nums[i] 处那个 0 换到 j，正好补上被移走的空位
  · 非零元素的相对顺序由 j 的扫描顺序保证：先遇到的先落到前面
  · 只有 nums[j] != 0 才交换；对 0 也交换会把 0 换回前面，顺序和归位都错
  · i == j 时交换是空操作，可以直接跳过以省下两次写（进阶问的操作次数）

以示例 1（nums = [0,1,0,3,12]）为例：
  j=0：nums[0]=0 跳过
  j=1：nums[1]=1 非零，swap(0,1) → [1,0,0,3,12]，i=1
  j=2：nums[2]=0 跳过
  j=3：nums[3]=3 非零，swap(1,3) → [1,3,0,0,12]，i=2
  j=4：nums[4]=12 非零，swap(2,4) → [1,3,12,0,0] ✔

复杂度分析：
  时间 O(n)：j 每个下标只访问一次
  空间 O(1)：只用了两个下标变量

解法二：双指针（两次遍历，先覆盖非零再补零）【最优解，与解法一并列】

先覆盖、后补零的两遍扫描。第一遍把所有非零元素按原顺序写到 nums[0..k-1]，
nums[k..n-1] 全部置 0。
  · 复杂度与解法一完全相同（时间 O(n)、空间 O(1)），按渐近判定并列最优
  · 写次数正好是 n：每个位置都被写过一次；解法一的交换次数等于非零元素
    个数（最多 n 次、每次两次写），所以零很少时解法二写得更少，零很多时
    解法一写得更少 —— 进阶问的"减少操作次数"没有单一答案
  · 第一遍的覆盖写是安全的：k 始终不大于当前读到的下标 j，读到的值在被
    覆盖之前就已经取出来了

以示例 1（nums = [0,1,0,3,12]）为例：
  第一遍收集：1、3、12 → [1,3,12,3,12]，k=3
  第二遍补零：下标 3、4 置 0 → [1,3,12,0,0] ✔

复杂度分析：
  时间 O(n)：两遍各扫一次，仍是线性
  空间 O(1)：只用了一个写指针
*/
class Solution1
{
public:
    void moveZeroes(vector<int> &nums)
    {
        // write：下一个非零元素该落的位置，也等于已归位的非零元素个数
        int write = 0;
        for (int j = 0; j < static_cast<int>(nums.size()); ++j)
        {
            if (nums[j] == 0) continue;

            // write < j 时 nums[write] 必然还是 0，交换等于把 0 挪到后面
            if (write != j) swap(nums[write], nums[j]);
            ++write;
        }
    }
};

class Solution2
{
public:
    void moveZeroes(vector<int> &nums)
    {
        int n = static_cast<int>(nums.size());
        int k = 0;
        for (int j = 0; j < n; ++j)
        {
            // k <= j：nums[k] 要么是已处理过的位置，要么正是 nums[j] 本身
            if (nums[j] != 0) nums[k++] = nums[j];
        }

        // 第一遍结束后 k..n-1 里的旧值是残留副本，统一抹成 0
        for (int i = k; i < n; ++i) nums[i] = 0;
    }
};

namespace
{
// 两种解法都要在同一个输入上得到完全相同的数组，顺序敏感，直接逐项比
void check(const vector<int> &input, const vector<int> &want)
{
    Solution1 s1;
    vector<int> a = input;
    s1.moveZeroes(a);
    assert(a == want);

    Solution2 s2;
    vector<int> b = input;
    s2.moveZeroes(b);
    assert(b == want);
}
} // namespace

int main()
{
    // 示例 1：两个 0 分散在中间，验证非零元素的相对顺序
    check({0, 1, 0, 3, 12}, {1, 3, 12, 0, 0});

    // 示例 2：单个 0，没有任何非零元素
    check({0}, {0});

    // 边界：全 0，一次交换都不该发生
    check({0, 0, 0, 0}, {0, 0, 0, 0});

    // 边界：没有 0，数组保持原样
    check({1, 2, 3}, {1, 2, 3});

    // 边界：负数和 INT_MIN 也是非零元素，不能被当成"空位"
    check({0, INT_MIN, 0, -3}, {INT_MIN, -3, 0, 0});

    // 反直觉：非零元素全挤在末尾，交换跨度最大
    check({0, 0, 0, 1}, {1, 0, 0, 0});

    // 边界：0 已经在末尾，不需要移动
    check({1, 2, 0}, {1, 2, 0});

    cout << "all tests passed" << endl;
    return 0;
}
