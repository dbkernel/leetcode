/*
============================================================================
283. 移动零（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/move-zeroes/
分类：双指针 · 原地数组重排

给定一个数组 nums，编写一个函数将所有 0 移动到数组的末尾，同时保持非零元素的
相对顺序。

请注意 ，必须在不复制数组的情况下原地对数组进行操作。

示例 1：
输入: nums = [0,1,0,3,12]
输出: [1,3,12,0,0]

示例 2：
输入: nums = [0]
输出: [0]

提示：
- 1 <= nums.length <= 10^4
- -2^31 <= nums[i] <= 2^31 - 1

进阶：你能尽量减少完成的操作次数吗？
*/

/*
解法一：双指针（一次遍历，非零元素与零原地交换）【最优解】

为什么慢：最直白的写法是"每遇到一个 0，就把后面整段往前挪一格，再在末尾
补 0"。挪动是逐元素拷贝，全 0 数组里第 i 个 0 要搬 n-i 个元素，总操作数
是 O(n^2)。另一种"先把非零元素收进新数组再拷回"时间 O(n)，但额外开了
O(n) 空间，直接违反题面的"不复制数组"。

换个角度：不要去搬 0，而是去收集非零元素。用 write 指向"下一个非零元素
应该落在哪里"，j 只负责从头到尾扫描：j 碰到非零就和 write 交换，write
前进一格。0 被交换动作自然甩到了后面，不需要单独处理。

关键点：
  · write 只在写入非零元素后前进，所以恒有 write <= j，交换的两个位置
    都在已扫描过的区间内，不会覆盖还没读到的元素
  · 用交换而不是赋值：赋值会把 j 处的非零元素留下两份，而交换把
    nums[write] 处那个 0 换到 j，正好补上被移走的空位
  · 非零元素的相对顺序由 j 的扫描顺序保证：先遇到的先落到前面
  · 只有 nums[j] != 0 才交换；对 0 也交换会把 0 换回前面
  · write == j 时交换是空操作，跳过它可以省下两次写（进阶问的操作次数）
  · Rust 的 `Vec::swap` 内部取两个 &mut，借用检查器认识这种写法，
    直接写 `let t = a; a = b; b = t;` 反而会因为两次可变借用报错

以示例 1（nums = [0,1,0,3,12]）为例：
  j=0：nums[0]=0 跳过
  j=1：nums[1]=1 非零，交换 0 与 1 → [1,0,0,3,12]，write=1
  j=2：nums[2]=0 跳过
  j=3：nums[3]=3 非零，交换 1 与 3 → [1,3,0,0,12]，write=2
  j=4：nums[4]=12 非零，交换 2 与 4 → [1,3,12,0,0] ✔

复杂度分析：
  时间 O(n)：j 每个下标只访问一次
  空间 O(1)：只用了两个下标变量

解法二：双指针（两次遍历，先覆盖非零再补零）【最优解，与解法一并列】

先覆盖、后补零的两遍扫描。第一遍把所有非零元素按原顺序写到 nums[0..k-1]，
nums[k..n-1] 全部置 0。
  · 复杂度与解法一完全相同（时间 O(n)、空间 O(1)），按渐近判定并列最优
  · 写次数正好是 n：每个位置都被写过一次；解法一的交换次数等于非零元素
    个数（每次两次写），所以零很少时解法二写得更少，零很多时解法一写得
    更少 —— 进阶问的"减少操作次数"没有单一答案
  · 第一遍的覆盖写是安全的：k 始终不大于当前读到的下标 j，读到的值在被
    覆盖之前就已经取出来了

以示例 1（nums = [0,1,0,3,12]）为例：
  第一遍收集：1、3、12 → [1,3,12,3,12]，k=3
  第二遍补零：下标 3、4 置 0 → [1,3,12,0,0] ✔

复杂度分析：
  时间 O(n)：两遍各扫一次，仍是线性
  空间 O(1)：只用了一个写指针
*/

// ---------- 解法一：一次遍历交换（最优解） ----------
// 力扣提交时平台给的是 `impl Solution`，本地单文件 rustc 没有类型，
// 所以这里显式定义；两个解法各用一个类型，避免同名方法冲突
pub struct Solution1;

impl Solution1 {
    pub fn move_zeroes(nums: &mut Vec<i32>) {
        let mut write = 0;
        for j in 0..nums.len() {
            if nums[j] == 0 {
                continue;
            }
            // write < j 时 nums[write] 必然还是 0，交换等于把 0 挪到后面
            if write != j {
                nums.swap(write, j);
            }
            write += 1;
        }
    }
}

// ---------- 解法二：两次遍历，先覆盖非零再补零（与解法一并列） ----------
pub struct Solution2;

impl Solution2 {
    pub fn move_zeroes(nums: &mut Vec<i32>) {
        let n = nums.len();
        let mut k = 0;
        for j in 0..n {
            // k <= j：nums[k] 要么是已处理过的位置，要么正是 nums[j] 本身
            if nums[j] != 0 {
                nums[k] = nums[j];
                k += 1;
            }
        }

        // 第一遍结束后 k..n-1 里的旧值是残留副本，统一抹成 0
        for i in k..n {
            nums[i] = 0;
        }
    }
}

// ===== 测试辅助 =====
fn check(input: &[i32], want: &[i32]) {
    let mut a = input.to_vec();
    Solution1::move_zeroes(&mut a);
    assert_eq!(a, want, "one-pass({input:?})");

    let mut b = input.to_vec();
    Solution2::move_zeroes(&mut b);
    assert_eq!(b, want, "two-pass({input:?})");
}

fn main() {
    // 示例 1：两个 0 分散在中间，验证非零元素的相对顺序
    check(&[0, 1, 0, 3, 12], &[1, 3, 12, 0, 0]);

    // 示例 2：单个 0，没有任何非零元素
    check(&[0], &[0]);

    // 边界：全 0，一次交换都不该发生
    check(&[0, 0, 0, 0], &[0, 0, 0, 0]);

    // 边界：没有 0，数组保持原样
    check(&[1, 2, 3], &[1, 2, 3]);

    // 边界：负数和 i32::MIN 也是非零元素，不能被当成"空位"
    check(&[0, i32::MIN, 0, -3], &[i32::MIN, -3, 0, 0]);

    // 反直觉：非零元素全挤在末尾，交换跨度最大
    check(&[0, 0, 0, 1], &[1, 0, 0, 0]);

    // 边界：0 已经在末尾，不需要移动
    check(&[1, 2, 0], &[1, 2, 0]);

    println!("all tests passed");
}
