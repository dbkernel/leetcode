"""
============================================================================
231. 2 的幂（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/power-of-two/
分类：位运算 · 最低位清除 / 约数判定

给你一个整数 n，请你判断该整数是否是 2 的幂次方。如果是，返回 true ；
否则，返回 false 。

如果存在一个整数 x 使得 n == 2^x ，则认为 n 是 2 的幂次方。

示例 1：
输入：n = 1
输出：true
解释：2^0 = 1

示例 2：
输入：n = 16
输出：true
解释：2^4 = 16

示例 3：
输入：n = 3
输出：false

提示：
- -2^31 <= n <= 2^31 - 1

进阶：你能够不使用循环/递归解决此问题吗？
"""


"""
解法一：反复除以 2，看最后是否剩下 1【非最优】

为什么慢：思路最直白，但代价是跟着数值走 —— 每除一次只能砍掉一个二进制的
0，n 有 31 位就要转 31 圈，时间 O(log n)。数据范围已经写明 n < 2^31，也就
是说最多 31 次，够用但不是最优。

换个角度：判断「是不是 2 的幂」本质是在问「二进制里是不是只有一个 1」。
除法是在逐个删掉低位的 0，删完还要比较；既然只看 1 的个数，直接对位下手
更快。

关键点：
  · 先挡掉 n <= 0：0 与负数都不是 2 的幂，不挡的话 0 进循环会死循环
  · 循环条件是 n % 2 == 0，偶数才继续除，奇数时停下
  · 结束后判 n == 1，不能判 n % 2 == 1（3 除到 3 也会是奇数）
  · Python 里 // 与 / 不同：判断整除要用 %，除法用 // 才不会变成浮点

以示例 2（n = 16）为例：
  16 → 8 → 4 → 2 → 1，循环结束且 n == 1 → true ✔
以示例 3（n = 3）为例：
  3 是奇数，不进循环，n == 3 != 1 → false ✔

复杂度分析：
  时间 O(log n)：每轮削掉一个二进制位，最坏 31 轮
  空间 O(1)：只改 n 本身

解法二：清除最低位的 1，看是否归零【最优解】

为什么慢：解法一要一位一位地除，循环次数随数值增长；而「只有一个 1」这个
性质用一次位运算就能验证，没必要逐位试。

换个角度：n & (n-1) 会把 n 最低位的那个 1 变成 0。若 n 是 2 的幂，二进制里
恰好只有一个 1，清掉之后就是 0；若有多个 1，清掉一个还剩别的，结果非 0。

关键点：
  · 必须先判 n > 0：Python 的负数是无限精度补码，负数与最小负数同样可能
    满足 n & (n-1) == 0（如 -2^31 的位模式只有一个 1）
  · 条件写成 n > 0 and (n & (n-1)) == 0，两个条件缺一不可
  · 不能写成 n & (n+1)：那只对「尾部全 1」成立
  · Python 的 & 对负数的结果按补码解释，不依赖固定位宽，判断仍然准确

以示例 2（n = 16，二进制 10000）为例：
  n-1 = 01111，与运算得 0 → true ✔
以示例 3（n = 3，二进制 11）为例：
  n-1 = 10，与运算得 10 ≠ 0 → false ✔
以 n = -2147483648 为例：
  位运算结果为 0，但 n > 0 不成立 → false ✔

复杂度分析：
  时间 O(1)：一次减法加一次与运算
  空间 O(1)：不需要额外空间

解法三：判断能否整除 2^31 范围内最大的 2 的幂【最优解，与解法二并列】

为什么慢：解法二已经是一次运算；它的短板在可推广性 —— 位技巧依赖补码表示，
换到不限位宽的整数模型时不再直观。而「2 的幂的约数仍是 2 的幂」这条性质只
依赖整除关系。

换个角度：题面约束是 32 位有符号整数，正数范围内最大的 2 的幂是
2^30 = 1073741824。任何不超过它的 2 的幂都能整除它；反过来，能整除 2^30 的
正整数，质因数分解里只能有 2，本身也必然是 2 的幂。

关键点：
  · 上限取 2^30 而不是 2^31：2^31 = 2147483648 已越过题面给出的正数范围
  · Python 的 int 没有位宽，上限必须按题面约束定，不能按语言类型宽度推
  · 仍要先判 n > 0，负数整除同样可能余 0（如 -2 整除 2^30）
  · 是 2^30 % n 而不是 n % 2^30：方向反了会把 0 和所有倍数都判成 true

以示例 2（n = 16）为例：
  1073741824 % 16 == 0 → true ✔
以示例 3（n = 3）为例：
  1073741824 % 3 != 0 → false ✔

复杂度分析：
  时间 O(1)：一次取模
  空间 O(1)：一个常量

取舍：解法二与解法三同为 O(1) 时间、O(1) 空间，都算最优解。解法二是一次与
运算，指令数最少，是本题的标准答案；解法三多一次除法（取模），常数略大，
但只用整除关系，不依赖补码的位模式，换到别的数值模型时更容易迁移。两者都
必须先挡住 n <= 0。
"""


class Solution1:
    def isPowerOfTwo(self, n: int) -> bool:
        # 0 与负数都不是 2 的幂；不挡 0 的话下面的循环不会终止
        if n <= 0:
            return False
        while n % 2 == 0:
            n //= 2
        return n == 1


class Solution2:
    def isPowerOfTwo(self, n: int) -> bool:
        # 负数与最小负数的位模式也可能只有一个 1，必须先靠符号拦掉
        return n > 0 and (n & (n - 1)) == 0


class Solution3:
    def isPowerOfTwo(self, n: int) -> bool:
        # 2^30 是题面 32 位有符号正数范围内最大的 2 的幂
        max_pow = 1073741824
        # 先判正，避免负数整除也余 0
        return n > 0 and max_pow % n == 0


def check(n: int, want: bool) -> None:
    assert Solution1().isPowerOfTwo(n) == want
    assert Solution2().isPowerOfTwo(n) == want
    assert Solution3().isPowerOfTwo(n) == want


if __name__ == "__main__":
    # 示例 1 / 2 / 3
    check(1, True)
    check(16, True)
    check(3, False)

    # 边界：0 不是 2 的幂
    check(0, False)

    # 边界：负数不是 2 的幂
    check(-16, False)
    check(-1, False)

    # 边界：最小负数的位模式只有一个 1，位运算拦不住，只能靠 n > 0
    check(-2147483648, False)

    # 边界：32 位正数范围内最大的 2 的幂及其一半
    check(1073741824, True)
    check(536870912, True)

    # 边界：紧邻 2 的幂的整数
    check(1073741825, False)
    check(2147483647, False)
    check(2, True)
    check(1024, True)
    check(5, False)

    print("all tests passed")
