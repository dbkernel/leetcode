"""
============================================================================
455. 分发饼干（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/assign-cookies/
分类：贪心 · 排序双指针

假设你是一位很棒的家长，想要给你的孩子们一些小饼干。但是，每个孩子最多
只能给一块饼干。

对每个孩子 i，都有一个胃口值 g[i]，这是能让孩子们满足胃口的饼干的最小
尺寸；并且每块饼干 j，都有一个尺寸 s[j] 。如果 s[j] >= g[i]，我们可以将
这个饼干 j 分配给孩子 i ，这个孩子会得到满足。你的目标是满足尽可能多的
孩子，并输出这个最大数值。

示例 1：
输入: g = [1,2,3], s = [1,1]
输出: 1
解释:
你有三个孩子和两块小饼干，3 个孩子的胃口值分别是：1,2,3。
虽然你有两块小饼干，由于他们的尺寸都是 1，你只能让胃口值是 1 的孩子满足。
所以你应该输出 1。

示例 2：
输入: g = [1,2], s = [1,2,3]
输出: 2
解释:
你有两个孩子和三块小饼干，2 个孩子的胃口值分别是：1,2。
你拥有的饼干数量和尺寸都足以让所有孩子满足。
所以你应该输出 2。

提示：
1 <= g.length <= 3 * 10^4
0 <= s.length <= 3 * 10^4
1 <= g[i], s[j] <= 2^31 - 1

注意：本题与 2410. 运动员和训练师的最大匹配数 题相同。
"""
from typing import List


"""
解法：排序 + 双指针（小饼干优先喂小胃口）【最优解】

为什么慢：不排序时，一块饼干该给哪个孩子没有依据，只能回溯枚举所有分配，
指数级；即使贪心地随意匹配，也可能把大饼干浪费在小胃口孩子身上，让后面
大胃口的孩子无饼干可用。

换个角度：把两个数组都升序排列后，「满足」关系变成一条单调的线：
小饼干能满足的孩子集合，是大饼干能满足集合的子集。于是从最小的饼干开始
依次尝试，只要能满足当前胃口最小的孩子就立刻给出 —— 这块饼干再留下去
也不会变得更有用。

关键点：
  · 两个数组都要排序，只排一边无法形成「小对小」的顺序
  · 饼干指针每轮必进；孩子指针只在分配成功时进
  · 饼干不够大时直接丢弃这块饼干，不能拿它去试更大的胃口
  · 返回的是孩子指针，也就是被满足的人数

为什么贪心是对的（相邻交换 / 无损替换）：
  · 设 c 是当前最小的一块饼干，i 是当前胃口最小的孩子。
  · 若 c < g[i]：i 的胃口已是剩余孩子里最小的，c 满足不了 i，就满足不了
    任何剩余孩子，丢弃 c 不会有损失。
  · 若 c >= g[i]：c 是所有剩余饼干中最小的，自然也是能满足 g[i] 的
    最小饼干。证明存在最优方案把 c 分给 i：
    - i 未匹配、c 未使用：加上 c→i 会多满足一人，与「最优」矛盾；
    - i 未匹配、c 给了孩子 j：把 c 改给 i，满足人数不变；
    - i 已匹配到 d（d >= c）：c 未使用时用 c 换 d；c 给了 j 时交换，
      i 拿 c、j 拿 d，由 g[j] <= c <= d 知 j 仍然满足。
    三种情况都不减少满足人数。
  · 于是总存在一个最优方案包含 c→i；删掉 i 与 c 后对剩余部分归纳，
    贪心每步都不劣于最优，最终人数就是最大值。
  · 从大到小看是同一论证：把最大的饼干 S 给它所能满足的最大胃口 i。
    若 i 原本拿 d（d <= S），用 S 换 d 仍然满足；若 S 原本给了胃口更小
    的 j，交换后 j 拿 d（d >= g[i] >= g[j]）也仍然满足。故这一步无损。

以示例 1（g = [1,2,3]，s = [1,1]）为例：
  s[0]=1 >= g[0]=1 → 满足 1 人，child=1
  s[1]=1 <  g[1]=2 → 丢弃这块饼干
  没有饼干了，返回 1 ✔

复杂度分析：
  时间 O(m log m + n log n)：两次排序占主导，双指针只扫一遍
  空间 O(log m + log n)：排序栈开销；不计排序则只用了两个下标
"""


class Solution:
    # 返回最多能满足的孩子数；g 为胃口，s 为饼干尺寸
    def findContentChildren(self, g: List[int], s: List[int]) -> int:
        g.sort()
        s.sort()

        child = 0  # 下一个待满足的孩子，也等于已满足人数
        cookie = 0
        while cookie < len(s) and child < len(g):
            # 这块饼干对剩下的所有孩子都没用（他们的胃口只会更大）
            if s[cookie] >= g[child]:
                child += 1
            cookie += 1
        return child


# 同时传入两家孩子的胃口与饼干，失败时能直接看到是哪一组
def check(g: List[int], s: List[int], want: int) -> None:
    assert Solution().findContentChildren(g, s) == want


if __name__ == "__main__":
    # 示例 1：饼干不够，只能满足胃口最小的那个
    check([1, 2, 3], [1, 1], 1)

    # 示例 2：饼干充足，两个孩子都能满足
    check([1, 2], [1, 2, 3], 2)

    # 边界：唯一一块饼干太小，一个也满足不了
    check([3], [1], 0)

    # 边界：没有饼干
    check([1, 2], [], 0)

    # 边界：尺寸恰好相等，等号必须算满足
    check([1, 1], [1, 1], 2)

    # 边界：一块大饼干只能给一个孩子，不能切开
    check([1, 2], [3], 1)

    # 反直觉：饼干很多但全都太小，数量不等于答案
    check([2, 3, 4], [1, 1, 1, 1], 0)

    # 边界：完全匹配
    check([1, 2, 3], [1, 2, 3], 3)

    print("all tests passed")
