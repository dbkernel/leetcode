/*
============================================================================
452. 用最少数量的箭引爆气球（中等）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/minimum-number-of-arrows-to-burst-balloons/
分类：贪心 · 区间调度（按右端点排序）

有一些球形气球贴在一堵用 XY 平面表示的墙面上。墙面上的气球记录在整数
数组 points ，其中 points[i] = [xstart, xend] 表示水平直径在 xstart 和
xend 之间的气球。你不知道气球的确切 y 坐标。

一支弓箭可以沿着 x 轴从不同点 完全垂直 地射出。在坐标 x 处射出一支箭，
若有一个气球的直径的开始和结束坐标为 xstart，xend， 且满足
xstart <= x <= xend，则该气球会被 引爆 。可以射出的弓箭的数量 没有限制 。
弓箭一旦被射出之后，可以无限地前进。

给你一个数组 points ，返回引爆所有气球所必须射出的 最小 弓箭数 。

示例 1：
输入：points = [[10,16],[2,8],[1,6],[7,12]]
输出：2
解释：气球可以用2支箭来爆破:
-在x = 6处射出箭，击破气球[2,8]和[1,6]。
-在x = 11处发射箭，击破气球[10,16]和[7,12]。

示例 2：
输入：points = [[1,2],[3,4],[5,6],[7,8]]
输出：4
解释：每个气球需要射出一支箭，总共需要4支箭。

示例 3：
输入：points = [[1,2],[2,3],[3,4],[4,5]]
输出：2
解释：气球可以用2支箭来爆破:
- 在x = 2处发射箭，击破气球[1,2]和[2,3]。
- 在x = 4处射出箭，击破气球[3,4]和[4,5]。

提示：
1 <= points.length <= 10^5
points[i].length == 2
-2^31 <= xstart < xend <= 2^31 - 1
*/
#include <algorithm>
#include <cassert>
#include <iostream>
#include <vector>
using namespace std;

/*
解法：按右端点升序排序，箭放在当前右端点【最优解】

为什么慢：直接枚举「在哪些坐标放箭」是指数级的；把问题看成图论的最小
点覆盖也不划算。瓶颈在于没想清楚「一支箭覆盖哪些气球」由什么决定。

换个角度：一支箭能覆盖一组气球，当且仅当这组区间的交集非空，而交集的
右端就是这组区间里最小的那个右端点。于是只要按右端点从小到大处理，
「当前右端点」就是最紧的约束：能共享这支箭的区间必须包含它。

关键点：
  · 必须按右端点排序，不能按左端点（反例见下）
  · 箭的位置初始化为第一个区间的右端点，箭数初始化为 1
  · 只有左端点 > 当前箭的位置时才补箭，等号表示仍能覆盖
  · 补箭后把位置更新为新气球的右端点，保持「最紧约束」
  · points 至少有一个元素，不用处理空输入（这里仍留了防御分支）

为什么贪心是对的（相邻交换）：
  · 排序后第一个气球是 [l1, r1]，r1 是所有右端点中最小的。
  · 任取一个最优方案，扎破气球 1 的箭落在 x ∈ [l1, r1]。把这支箭移到
    r1：任何被 x 扎破的气球 i 满足 l_i <= x <= r_i；由排序 r_i >= r1，
    且 x <= r1，所以 l_i <= x <= r1 <= r_i，r1 也能扎破它。
    移动后不丢气球，箭数不变，故存在第一支箭就在 r1 的最优方案。
  · 接着删掉所有包含 r1 的气球（右端点 >= r1，所以等价于 l_i <= r1），
    剩余气球都满足 l_i > r1，问题变成同一形式的子问题，归纳即可。
  · 每一步都不劣于最优，所以贪心箭数等于最小箭数。

为什么按左端点排序会错：
  · 反例 [[1,2],[2,3],[3,4]]。按左端点排序后，如果对每个未被覆盖的
    气球朝它的左端点补箭，会依次射 1、2、3 共 3 支；而最优只要 2 支
    （x=2 覆盖前两个，x=4 覆盖最后一个）。
  · 根因：决定「还能不能共享一支箭」的是最小的右端点，不是左端点。
    左端点排序没有把这个最紧约束摆在最前面。

以示例 1（points = [[10,16],[2,8],[1,6],[7,12]]）为例：
  按右端点排序：[1,6], [2,8], [7,12], [10,16]
  箭放在 6，覆盖 [1,6]、[2,8]
  [7,12] 的左端点 7 > 6 → 补第二支箭，位置 12，覆盖 [7,12]、[10,16]
  共 2 支 ✔

复杂度分析：
  时间 O(n log n)：排序占主导，之后一趟线性扫描
  空间 O(log n)：排序的栈开销；不计排序只用了箭数与位置两个变量
*/
class Solution
{
public:
    // 返回引爆所有气球所需的最小箭数
    int findMinArrowShots(vector<vector<int>> &points)
    {
        if (points.empty()) return 0;

        sort(points.begin(), points.end(),
             [](const vector<int> &a, const vector<int> &b)
             {
                 return a[1] < b[1];
             });

        int arrows = 1;
        int pos = points[0][1]; // 当前这支箭的横坐标
        for (size_t i = 1; i < points.size(); ++i)
        {
            // 左端点已经越过箭的位置，这支箭够不到它
            if (points[i][0] > pos)
            {
                ++arrows;
                pos = points[i][1];
            }
        }
        return arrows;
    }
};

namespace
{
// 传值接收，排序不会影响调用方；失败时能看到完整用例
void check(vector<vector<int>> points, int want)
{
    Solution solution;
    assert(solution.findMinArrowShots(points) == want);
}
} // namespace

int main()
{
    // 示例 1：两支箭分别覆盖两对区间
    check({{10, 16}, {2, 8}, {1, 6}, {7, 12}}, 2);

    // 示例 2：四个区间互不相交，每个都要单独一支
    check({{1, 2}, {3, 4}, {5, 6}, {7, 8}}, 4);

    // 示例 3：端点相接，等号必须算覆盖
    check({{1, 2}, {2, 3}, {3, 4}, {4, 5}}, 2);

    // 关键反例：按左端点排序并朝左端点补箭会得到 3 支
    check({{1, 2}, {2, 3}, {3, 4}}, 2);

    // 边界：单个气球
    check({{1, 2}}, 1);

    // 反直觉：最大区间包住两个小区间，箭仍要两支（3 与 4 不重合）
    check({{1, 10}, {2, 3}, {4, 5}}, 2);

    // 边界：两个气球只在端点相交
    check({{1, 2}, {2, 3}}, 1);

    // 边界：负数坐标，排序与比较逻辑不变
    check({{-5, -3}, {-4, -1}, {-2, 0}}, 2);

    // 边界：全部区间共享公共点，一支箭足够
    check({{1, 4}, {2, 5}, {3, 6}}, 1);

    cout << "all tests passed" << endl;
    return 0;
}
