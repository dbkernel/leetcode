"""
============================================================================
461. 汉明距离（简单）
来源：力扣（LeetCode）
链接：https://leetcode.cn/problems/hamming-distance/
分类：位运算 · 异或 + 汉明重量

两个整数之间的 汉明距离 指的是这两个数字对应二进制位不同的位置的数目。

给你两个整数 x 和 y，计算并返回它们之间的汉明距离。

示例 1：
输入：x = 1, y = 4
输出：2
解释：
1   (0 0 0 1)
4   (0 1 0 0)
       ↑   ↑
上面的箭头指出了对应二进制位不同的位置。

示例 2：
输入：x = 3, y = 1
输出：1

提示：
- 0 <= x, y <= 2^31 - 1

注意：本题与 2220. 转换数字的最少位翻转次数 相同。
"""


"""
解法一：异或后逐位检查（固定 32 轮）【非最优】

为什么慢：异或已经把「哪些位不同」压进一个数，可逐位检查仍要走满 32 轮 ——
x 与 y 完全相同时答案是 0，也要白跑 32 次。代价与答案无关。

换个角度：答案就是 diff = x ^ y 的汉明重量，于是问题直接退回 191：只有
diff 里那些为 1 的位值得处理。

关键点：
  · 必须先异或再数 1：分别数两边的 1 再相减是错的，1 的个数之差并不等于
    不同位的个数
  · x、y 非负，异或结果也非负，Python 里不会冒出一堆前导 1；靠循环上界
    32 把考察范围钉死在题目的 32 位域内
  · 循环上界写 32 而不是 31 或 64：题目口径就是 32 位

手推一遍（x = 1，y = 4）：
  0001 ^ 0100 = 0101
  第 0 位为 1 → count = 1；第 2 位为 1 → count = 2
  其余位为 0，跑满 32 轮 → 2 ✔

复杂度分析：
  时间 O(w)：w 固定为 32，与不同的位数无关
  空间 O(1)：只用一个计数器

解法二：异或 + n & (n - 1)【最优解】

为什么慢：解法一慢在轮数与答案脱钩。差异位往往很少，却照样转满 32 轮。

换个角度：既然答案就是 diff 里 1 的个数，就让每一轮抹掉一个 1，
diff &= diff - 1。轮数等于答案，输入越「像」就越快。

关键点：
  · 终止条件是 diff == 0，清位一定会走到 0，不存在死循环
  · Python 的整数是任意精度，没有补码溢出问题：x、y 非负，结果与
    C++/Go/Rust 完全一致
  · 计数在清位之后，顺序反了会少算最后一次

手推一遍（x = 1，y = 4）：
  diff = 0101
  0101 & 0100 = 0100 → count = 1
  0100 & 0011 = 0000 → count = 2
  diff == 0 结束 → 2 ✔（只转了 2 轮）

复杂度分析：
  时间 O(k)：k 为不同位的个数，最坏 32
  空间 O(1)：只用一个计数器

解法三：异或 + 内置 popcount【最优解，与解法二并列】

这一条不是「更慢」，而是把数 1 交给内建能力：bin 转成字符串后统计字符
"1" 的个数，实际由 C 层一次扫描完成。

换个角度：汉明距离就是 popcount(x ^ y)，内建支持这个度量。

关键点：
  · 用 bin(diff).count("1")，不要用字符串切片的技巧，后者在 diff = 0 时
    容易算成 1
  · 异或前不必加掩码：x、y 非负，diff 的高位没有多余的 1
  · 面试通常要求手写解法二，内置函数只作为工程上的捷径

手推一遍（x = 1，y = 4）：
  bin(1 ^ 4) = "0b101"，数 "1" 得 2 ✔

复杂度分析：
  时间 O(w)：扫描 w 位二进制串，w 固定为 32
  空间 O(w)：临时字符串，w 固定为 32
"""


class Solution1:
    def hammingDistance(self, x: int, y: int) -> int:
        diff = x ^ y
        count = 0
        for bit in range(32):
            if diff & (1 << bit):
                count += 1
        return count


class Solution2:
    def hammingDistance(self, x: int, y: int) -> int:
        diff = x ^ y
        count = 0
        # 清位一定能把 32 位域清空，所以 diff == 0 是可靠的终止条件
        while diff:
            diff &= diff - 1
            count += 1
        return count


class Solution3:
    def hammingDistance(self, x: int, y: int) -> int:
        return bin(x ^ y).count("1")


def check(x: int, y: int, want: int) -> None:
    assert Solution1().hammingDistance(x, y) == want
    assert Solution2().hammingDistance(x, y) == want
    assert Solution3().hammingDistance(x, y) == want


if __name__ == "__main__":
    # 示例 1：差异位是第 0 位与第 2 位
    check(1, 4, 2)

    # 示例 2：只有最低位不同
    check(3, 1, 1)

    # 边界：完全相同，答案是 0，任何一轮都不该被计数
    check(0, 0, 0)
    check(12345, 12345, 0)

    # 边界：顺序无所谓，异或是对称的
    check(4, 1, 2)

    # 边界：第 30 位参与比较（2^30 与 0）
    check(1 << 30, 0, 1)

    # 边界：一方为 0，答案退化为另一方的汉明重量
    check(0, 2147483645, 30)

    print("all tests passed")
